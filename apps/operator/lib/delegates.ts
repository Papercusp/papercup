/**
 * Delegate session-management helpers.
 *
 * A delegate is an agent CLI process (omp -p with `-r <prefix>` or
 * claude -p with `--session-id <uuid>`, depending on AGENT_BACKEND) that
 * the operator spawns to handle anything beyond reflexive UI commands —
 * agent dispatch, multi-step research, anything that needs deep
 * reasoning. The user resumes them from the Delegates tab in the
 * operator panel.
 *
 * Server-side only. Backed by `harness_shared.delegates` PG table.
 * (The `agent_session_id` column name is kept for back-compat; it
 * actually stores either backend's session identifier.)
 *
 * Three layers of memory (kept small, regenerated lazily):
 *   1. Title — 5-10 words generated by haiku-4-5 after the first turn
 *   2. Summary — 40-60 words regenerated every 5 turns or on 5min idle
 *   3. The actual `claude --resume` conversation (Claude truncates as needed)
 *
 * The DB column `agent_session_id` is the uuid passed to claude -p as
 * `--session-id`. Field is named `agentSessionId` in the row type for
 * the same reason — it's the key we hand back to the CLI to resume.
 */

import { withWorkspace } from '@restart/db-org';

export interface DelegateTurn {
  ts: string;          // ISO8601
  request: string;     // user request
  response: string;    // agent's full text reply
}

export interface DelegateRow {
  id: number;
  workspace: string;
  agentSessionId: string;
  title: string | null;
  summary: string | null;
  status: 'open' | 'archived';
  createdAt: string;
  lastActiveAt: string;
  turnCount: number;
  origin: 'voice' | 'panel' | 'oracle';
  initiatorMsg: string | null;
  /** Conversation history appended on every delegate-chat `done`. Empty
   *  for sessions started before migration 007. */
  transcript: DelegateTurn[];
}

export interface ListDelegatesArgs {
  workspace: string;
  status?: 'open' | 'archived' | 'all';
  limit?: number;
}

export async function listDelegates(args: ListDelegatesArgs): Promise<DelegateRow[]> {
  const status = args.status ?? 'open';
  const limit = Math.min(50, Math.max(1, args.limit ?? 20));
  return withWorkspace(args.workspace, async (tx) => {
    const rows = status === 'all'
      ? await tx`
          SELECT id, workspace, agent_session_id, title, summary, status,
                 created_at, last_active_at, turn_count, origin, initiator_msg, transcript
          FROM harness_shared.delegates
          WHERE workspace = ${args.workspace}
          ORDER BY last_active_at DESC
          LIMIT ${limit}
        `
      : await tx`
          SELECT id, workspace, agent_session_id, title, summary, status,
                 created_at, last_active_at, turn_count, origin, initiator_msg, transcript
          FROM harness_shared.delegates
          WHERE workspace = ${args.workspace} AND status = ${status}
          ORDER BY last_active_at DESC
          LIMIT ${limit}
        `;
    return rows.map((r) => normalize(r));
  });
}

export interface SearchDelegatesArgs {
  workspace: string;
  query: string;
  limit?: number;
}

export async function searchDelegates(args: SearchDelegatesArgs): Promise<DelegateRow[]> {
  const limit = Math.min(50, Math.max(1, args.limit ?? 10));
  const needle = `%${args.query.replace(/[%_]/g, (c) => '\\' + c)}%`;
  return withWorkspace(args.workspace, async (tx) => {
    const rows = await tx`
      SELECT id, workspace, agent_session_id, title, summary, status,
             created_at, last_active_at, turn_count, origin, initiator_msg, transcript
      FROM harness_shared.delegates
      WHERE workspace = ${args.workspace}
        AND (
             COALESCE(title, '')          ILIKE ${needle}
          OR COALESCE(summary, '')        ILIKE ${needle}
          OR COALESCE(initiator_msg, '')  ILIKE ${needle}
        )
      ORDER BY last_active_at DESC
      LIMIT ${limit}
    `;
    return rows.map((r) => normalize(r));
  });
}

export async function getDelegate(workspace: string, sessionRef: string): Promise<DelegateRow | null> {
  return withWorkspace(workspace, async (tx) => {
    const rows = await tx`
      SELECT id, workspace, agent_session_id, title, summary, status,
             created_at, last_active_at, turn_count, origin, initiator_msg, transcript
      FROM harness_shared.delegates
      WHERE workspace = ${workspace}
        AND (agent_session_id = ${sessionRef} OR id::text = ${sessionRef})
      LIMIT 1
    `;
    return rows.length > 0 ? normalize(rows[0]) : null;
  });
}

export async function createDelegate(args: {
  workspace: string;
  agentSessionId: string;
  origin: 'voice' | 'panel' | 'oracle';
  initiatorMsg: string;
  /** Backend that handled the spawn. Defaults to current AGENT_BACKEND
      env (omp | claude-code | claude); falls back to 'omp' if unset, matching
      the system-wide default. */
  agentBackend?: 'claude-code' | 'omp';
}): Promise<DelegateRow> {
  const env = (process.env.AGENT_BACKEND ?? '').toLowerCase();
  const fromEnv: 'claude-code' | 'omp' | null =
    env === 'omp' || env === 'pi' ? 'omp'
    : env === 'claude-code' || env === 'claude' ? 'claude-code'
    : null;
  const backend = args.agentBackend ?? fromEnv ?? 'omp';
  return withWorkspace(args.workspace, async (tx) => {
    const rows = await tx`
      INSERT INTO harness_shared.delegates (
        workspace, agent_session_id, origin, initiator_msg, turn_count, agent_backend
      ) VALUES (
        ${args.workspace}, ${args.agentSessionId}, ${args.origin}, ${args.initiatorMsg}, 1, ${backend}
      )
      RETURNING id, workspace, agent_session_id, title, summary, status,
                created_at, last_active_at, turn_count, origin, initiator_msg, transcript
    `;
    return normalize(rows[0]);
  });
}

export async function bumpDelegate(workspace: string, agentSessionId: string): Promise<void> {
  await withWorkspace(workspace, async (tx) => {
    await tx`
      UPDATE harness_shared.delegates
      SET turn_count = turn_count + 1,
          last_active_at = now()
      WHERE workspace = ${workspace} AND agent_session_id = ${agentSessionId}
    `;
  });
}

