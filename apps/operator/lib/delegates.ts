/**
 * Auto-archive delegates idle for >24h. Called from the delegate-chat
 * endpoint as a piggyback maintenance task; cheap, runs once per turn.
 */
export async function autoArchiveIdleDelegates(workspace: string): Promise<number> {
  return withWorkspace(workspace, async (tx) => {
    const rows = await tx`
      UPDATE harness_shared.delegates
      SET status = 'archived'
      WHERE workspace = ${workspace}
        AND status = 'open'
        AND last_active_at < now() - interval '24 hours'
      RETURNING id
    `;
    return rows.length;
  });
}

function normalize(r: any): DelegateRow {
  return {
    id: Number(r.id),
    workspace: r.workspace,
    agentSessionId: r.agent_session_id,
    title: r.title,
    summary: r.summary,
    status: r.status,
    createdAt: r.created_at?.toISOString?.() ?? r.created_at,
    lastActiveAt: r.last_active_at?.toISOString?.() ?? r.last_active_at,
    turnCount: Number(r.turn_count),
    origin: r.origin,
    initiatorMsg: r.initiator_msg,
    transcript: Array.isArray(r.transcript) ? r.transcript : [],
  };
}

/**
 * Append a turn to the delegate's transcript. Called from
 * /api/agent-mcp/delegate-chat after the SSE stream emits `done`. The
 * append is concurrency-safe at the row level via JSONB ||.
 */
export async function appendDelegateTurn(
  workspace: string,
  agentSessionId: string,
  turn: DelegateTurn,
): Promise<void> {
  await withWorkspace(workspace, async (tx) => {
    await tx`
      UPDATE harness_shared.delegates
      SET transcript = transcript || ${JSON.stringify([turn])}::jsonb
      WHERE workspace = ${workspace} AND agent_session_id = ${agentSessionId}
    `;
  });
}
