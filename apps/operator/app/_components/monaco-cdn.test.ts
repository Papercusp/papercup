/**
 * Guard: Monaco must never fetch the editor from the public internet.
 *
 * cdn-egress-fixes-2026-08-02 P-001, and the direct sibling of vditor-cdn.test.ts
 * next door — same class of bug, same shape of guard.
 *
 * `@monaco-editor/react` does not bundle the editor. It resolves it at runtime
 * through an AMD loader whose base path DEFAULTS to
 * `https://cdn.jsdelivr.net/npm/monaco-editor@0.55.1/min/vs`. We never called
 * `loader.config()`, so opening any code surface fetched ~4MB across the
 * internet before it could paint (~11MB once the TypeScript worker loaded), and
 * — the half that is easy to miss — RAN 0.55.1 while package.json installs
 * 0.56.0, a version nothing in CI ever typechecked.
 *
 * THE FAILURE MODE THIS GUARDS is quiet and per-surface: `paths.vs` is an
 * OPTIONAL setting with a WORKING default, so a new Monaco call site that
 * forgets the runtime import does not throw, does not warn, and looks perfect on
 * a fast connection — it just silently reintroduces the multi-megabyte fetch for
 * its own surface. Nothing else in the build would notice, which is precisely
 * why this has to be a source-level assertion.
 */
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { listLiveTypeScriptFiles } from './live-source-files';
import { stripJsComments } from './strip-js-comments';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '../../../..');
const MONACO_RUNTIME = resolve(HERE, 'monaco-runtime.ts');
const SETUP_SCRIPT = resolve(REPO_ROOT, 'apps/operator/scripts/setup-monaco-runtime.sh');

/** The side-effect import that points the loader at the local mirror. */
const RUNTIME_IMPORT = /@\/app\/_components\/monaco-runtime/;

/**
 * Drop comments before pattern-matching. Load-bearing, not tidiness — the same
 * lesson vditor-cdn.test.ts learned the hard way: the modules under test
 * DOCUMENT the thing being matched in prose ("Without it Monaco fetches ~4MB"),
 * and this file's own subject discusses `@monaco-editor/react` in its header. A
 * naive match counts those mentions as call sites. A guard that miscounts the
 * thing it guards is worse than no guard, because the noise is what gets
 * silenced.
 *
 * The shared single-pass scanner, NOT the two-regex form both CDN guards
 * originally carried: that version strips block comments first, so a `/*` inside
 * a LINE comment (HarnessPluginsSection.tsx line 8 contains `.claude/​*`) opens a
 * phantom block comment and swallows the real import 17 lines later. See
 * strip-js-comments.ts.
 */
const stripComments = stripJsComments;

/** Real, live call sites — excludes tests (which mock the module) and the
 *  retired web app under libs/papercusp/_retired (guarded by lint:no-retired). */
async function liveMonacoCallSites(): Promise<string[]> {
  const candidates = (await listLiveTypeScriptFiles(REPO_ROOT))
    .filter(Boolean)
    .filter((f) => !f.includes('.test.'))
    .filter((f) => !f.includes('_retired/'));

  const sites: string[] = [];
  for (const file of candidates) {
    const code = stripComments(await readFile(resolve(REPO_ROOT, file), 'utf8'));
    if (/@monaco-editor\/react/.test(code)) sites.push(file);
  }
  return sites.sort();
}

describe('monaco cdn (cdn-egress-fixes-2026-08-02 P-001)', () => {
  it('enumerates source files without a load-sensitive child process', async () => {
    const enumerator = await readFile(resolve(HERE, 'live-source-files.ts'), 'utf8');
    expect(enumerator).not.toMatch(/node:child_process|exec(?:File)?(?:Sync)?|spawn(?:Sync)?/);
  });

  it('every live Monaco call site imports the runtime config', async () => {
    const sites = await liveMonacoCallSites();

    // Four today: Gym dashboard, harness Plugins, dev SQL tab, editor-demo pane.
    expect(sites.length).toBeGreaterThanOrEqual(4);

    const missing: string[] = [];
    for (const file of sites) {
      const code = stripComments(await readFile(resolve(REPO_ROOT, file), 'utf8'));
      if (!RUNTIME_IMPORT.test(code)) missing.push(file);
    }

    // Named, not counted: the failure message has to say WHICH surface will
    // silently start fetching from jsdelivr, or the next person has to re-derive
    // it from a bare "expected 4 to be 5".
    expect(missing, `Monaco call sites missing the local-mirror import: ${missing.join(', ')}`).toEqual([]);
  });

  it('the loader base resolves to a real local mirror, not the internet', async () => {
    const src = await readFile(MONACO_RUNTIME, 'utf8');
    const base = src.match(/export const MONACO_VS_PATH = '([^']+)'/)?.[1];

    expect(base).toBeTruthy();
    // A protocol-bearing base is the regression: that is jsdelivr again.
    expect(base).toMatch(/^\//);
    expect(base).not.toMatch(/^https?:|^\/\//);
  });

  it('the mirror is regenerated by install AND by build, not by hand', async () => {
    // A gitignored mirror that only one of the two paths populates is a deploy
    // that renders no editor at all — the vditor mirror is wired into both for
    // exactly this reason, and monaco must match.
    const operatorPkg = JSON.parse(
      await readFile(resolve(REPO_ROOT, 'apps/operator/package.json'), 'utf8'),
    ) as { scripts?: Record<string, string> };
    const vitePkg = JSON.parse(
      await readFile(resolve(REPO_ROOT, 'apps/operator-vite/package.json'), 'utf8'),
    ) as { scripts?: Record<string, string> };

    expect(operatorPkg.scripts?.postinstall).toContain('setup-monaco-runtime.sh');
    expect(vitePkg.scripts?.prebuild).toContain('setup-monaco-runtime.sh');
  });

  it('reconciles the complete generated public root before its early-exit path', async () => {
    const script = await readFile(SETUP_SCRIPT, 'utf8');

    // The mirror owns the whole public/monaco root, not only the current vs
    // directory. This prevents an older nested mirror from being copied into
    // dist after the stamp makes the refresh a no-op.
    expect(script).toContain('ROOT="public/monaco"');
    expect(script).toContain('find "$ROOT" -mindepth 1 -maxdepth 1');
    expect(script).toContain('! -path "$DEST"');
    expect(script).toContain('! -path "$STAMP"');
    expect(script).toContain('-exec rm -rf -- {} +');

    const reconcileCall = script.indexOf('\nprune_owned_root\n');
    const versionRead = script.indexOf('VERSION=');
    const earlyExit = script.indexOf('monaco-runtime: already current');
    expect(reconcileCall).toBeGreaterThanOrEqual(0);
    expect(versionRead).toBeGreaterThanOrEqual(0);
    expect(reconcileCall).toBeGreaterThan(versionRead);
    expect(earlyExit).toBeGreaterThan(reconcileCall);
  });

  it('side-effect imports are not tree-shakeable in this tree', async () => {
    // The fix depends on a bare `import '.../monaco-runtime'` surviving the
    // bundler. That is only guaranteed while no package in the chain declares
    // `sideEffects: false` — so guard the ASSUMPTION, not just the code. If a
    // future dependency-hygiene pass adds the field, this fails loudly here
    // instead of silently un-fixing every Monaco surface at runtime.
    for (const pkg of ['package.json', 'apps/operator/package.json', 'apps/operator-vite/package.json']) {
      const parsed = JSON.parse(await readFile(resolve(REPO_ROOT, pkg), 'utf8')) as {
        sideEffects?: unknown;
      };
      expect(parsed.sideEffects, `${pkg} declares sideEffects — the monaco-runtime import can be dropped`).toBeUndefined();
    }
  });

  it('@monaco-editor/loader is a DECLARED dependency, not a transitive one', async () => {
    // monaco-runtime.ts imports it directly. Relying on it being hoisted as a
    // transitive dep of @monaco-editor/react is how a working import breaks
    // silently when the parent bumps its own dependency range.
    const pkg = JSON.parse(
      await readFile(resolve(REPO_ROOT, 'apps/operator/package.json'), 'utf8'),
    ) as { dependencies?: Record<string, string> };

    expect(pkg.dependencies?.['@monaco-editor/loader']).toBeTruthy();
  });
});
