'use client';

import { useCallback, useEffect, useState } from 'react';

interface Status {
  running: boolean;
  pid?: number;
  port?: number;
  since?: number;
  lastStderr?: string;
}

export default function StudioTab() {
  const [s, setS] = useState<Status>({ running: false });
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    try {
      const r = await fetch('/api/dev/drizzle-studio', { cache: 'no-store' });
      setS(await r.json());
    } catch (e: any) {
      setErr(String(e?.message ?? e));
    }
  }, []);

  useEffect(() => {
    void refresh();
    const t = setInterval(refresh, 2500);
    return () => clearInterval(t);
  }, [refresh]);

  const start = useCallback(async () => {
    setBusy(true);
    setErr(null);
    try {
      const r = await fetch('/api/dev/drizzle-studio', { method: 'POST' });
      const d = await r.json();
      setS(d);
      if (d.error) setErr(d.error);
    } catch (e: any) {
      setErr(String(e?.message ?? e));
    } finally {
      setBusy(false);
    }
  }, []);

  const stop = useCallback(async () => {
    setBusy(true);
    try {
      await fetch('/api/dev/drizzle-studio', { method: 'DELETE' });
      await refresh();
    } finally {
      setBusy(false);
    }
  }, [refresh]);

  const studioUrl = s.port ? `https://local.drizzle.studio/?host=127.0.0.1&port=${s.port}` : null;

  return (
    <div className="pc-dev-panel" style={{ display: 'flex', flexDirection: 'column', height: '100%' }}>
      <div style={{ padding: '12px 16px', borderBottom: '1px solid var(--pc-border)', display: 'flex', alignItems: 'center', gap: 12 }}>
        <strong>Drizzle Studio</strong>
        <span style={{ fontSize: 12, opacity: 0.7 }}>
          {s.running ? `running on :${s.port}` : 'stopped'}
        </span>
        <div style={{ flex: 1 }} />
        {s.running ? (
          <>
            <a
              href={studioUrl ?? '#'}
              target="_blank"
              rel="noopener noreferrer"
              className="pc-button"
              style={{ textDecoration: 'none' }}
            >
              Open in new tab ↗
            </a>
            <button className="pc-button" disabled={busy} onClick={stop}>
              Stop
            </button>
          </>
        ) : (
          <button className="pc-button" disabled={busy} onClick={start}>
            {busy ? 'Starting…' : 'Start Drizzle Studio'}
          </button>
        )}
      </div>
      {err && (
        <div style={{ padding: '8px 16px', color: 'var(--pc-fg-warn, #c33)', fontSize: 13 }}>{err}</div>
      )}
      {s.lastStderr && !s.running && (
        <pre style={{ padding: '8px 16px', fontSize: 12, color: 'var(--pc-fg-muted)', whiteSpace: 'pre-wrap' }}>
          {s.lastStderr}
        </pre>
      )}
      <div style={{ flex: 1, minHeight: 0 }}>
        {s.running && studioUrl ? (
          <iframe
            src={studioUrl}
            style={{ width: '100%', height: '100%', border: 'none', display: 'block' }}
            title="Drizzle Studio"
            sandbox="allow-scripts allow-same-origin allow-forms allow-popups"
          />
        ) : (
          <div style={{ padding: 24, color: 'var(--pc-fg-muted)', fontSize: 14, lineHeight: 1.6 }}>
            <p>
              Drizzle Studio is the official table inspector for the schema generated by the Drizzle
              migration. It connects to the local Postgres instance via the <code>harness_admin</code>{' '}
              role and reads from the auto-introspected schema at{' '}
              <code>libs/papercusp/libs/db/src/schema/generated.ts</code>.
            </p>
            <p>Click <strong>Start Drizzle Studio</strong> above to launch the gateway and embed it here.</p>
            <p style={{ opacity: 0.7, fontSize: 12 }}>
              The gateway runs as a child of this Next.js server and exits when the operator does. Some
              browsers block iframing <code>local.drizzle.studio</code> — use <strong>Open in new tab</strong>{' '}
              if the embed shows blank.
            </p>
          </div>
        )}
      </div>
    </div>
  );
}
