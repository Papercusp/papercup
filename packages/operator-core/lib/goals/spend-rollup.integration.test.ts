/**
 * spend-rollup.integration.test — the P-005 goal spend rollup against a real
 * Postgres (goal-mode-design-intent-hardening-2026-08-16, D-003).
 *
 * Behaviors a fake-sql unit test can't prove (same lesson as
 * convert.integration.test.ts: the unit-mocked halves had "never been proven to
 * compose"):
 *  - the POT leg (goalSpend, real @papercusp/db-org SQL) and the SESSION leg
 *    (sessionSpendForGoal) partition the ledger EXACTLY — a sample carrying both
 *    a goal-pot harness AND a goal-member session id is counted ONCE (by the pot
 *    leg), which only real SQL executing the NOT IN exclusion can demonstrate;
 *  - the goal-lifetime lower bound (GREATEST vs goals.created_at) on BOTH legs;
 *  - the metadata merge write: authoritative spentCents remains exactly the
 *    goals:pots leg while session attribution stays diagnostic-only;
 *  - the sweep's scope: ACTIVE goals only, flag-gated per tick.
 *
 * The falsifiability control for the dedup claim is the exact-cents assertion:
 * an implementation missing the pot-harness exclusion measures 255c here, one
 * missing the session leg measures 150c, one missing the pot leg measures 55c —
 * the asserted 205c is reachable only by the correct partition.
 */
