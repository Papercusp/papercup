/**
 * release-canonical-version-writeback.test.ts — WI-10001570.
 *
 * THE BUG THIS PINS: `release-local.sh` derives `ROOT` from where the script lives, so a
 * cut launched against an isolated worktree (`release:cut { root }`) bumped the version
 * ONLY inside that throwaway checkout. That worktree's `papercusp-desktop/.git` is an
 * INDEPENDENT clone — not a linked worktree sharing an object store — and the git push /
 * gh release leg is DELETED under LOCAL-only. So the bump commit reached the canonical
 * repo by no route at all and died with the worktree. That is how 0.0.18 shipped while
 * every canonical manifest still read 0.0.17, and why the desktop app kept reporting a
 * version that was never cut.
 *
 * The failure is SILENT at cut time: the cut succeeds, the artifacts are valid and signed,
 * and nothing is observably wrong until a release later when a source build still reports
 * the previous version. That is what makes the guards below load-bearing rather than
 * decorative — there is no other moment at which this class announces itself.
 *
 * Running a real cut needs a signing chain + toolchains, so per this repo's
 * regex-extraction convention (see release-submodule-freshness-fail-closed.test.ts) this
 * extracts the REAL `bump_version_manifests` helper verbatim from the shipping script and
 * evals it under bash against throwaway checkouts. Copying the logic into the test instead
 * would pin a copy and let the shipped script drift away from it freely.
 *
 *   cd packages/operator-core && npx vitest run lib/release-canonical-version-writeback.test.ts
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { afterEach, describe, expect, it } from 'vitest';

import { buildCutEnv } from './release-cut-launch';
import { RELEASE_RESUME_VERSION_PATHS, validateReleaseResumeResidue } from './agent-tools/release/cut';

function repoRoot(): string {
  let dir = dirname(fileURLToPath(import.meta.url));
  for (let i = 0; i < 12; i++) {
    if (existsSync(join(dir, 'papercusp-desktop', 'bin', 'release-local.sh'))) return dir;
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error('could not locate the repo root (no papercusp-desktop/bin/release-local.sh above this test)');
}

const ROOT = repoRoot();
// Overridable so scripts/mutation-probe.sh can prove these guards are falsifiable against a
// COPY outside the tree (tier 2), instead of mutating the shared checkout the fleet is using.
const SCRIPT_PATH = process.env.PROBE_SCRIPT ?? join(ROOT, 'papercusp-desktop', 'bin', 'release-local.sh');
const SCRIPT = readFileSync(SCRIPT_PATH, 'utf8');

// Extract the helper verbatim: `bump_version_manifests() {` through its closing brace at
// column 0. The embedded python heredoc contains no line that is a bare `}`, so the
// non-greedy match cannot terminate early inside it.
const HELPER_RE = /bump_version_manifests\(\)\s*\{[\s\S]*?\nPY\n\}\n/;

function helperSource(): string {
  const match = SCRIPT.match(HELPER_RE);
  expect(match, 'could not locate bump_version_manifests() in release-local.sh').toBeTruthy();
  return match![0];
}

/** Every real invocation of the helper — its definition, and any comment naming it, excluded. */
function callSites(): string[] {
  return SCRIPT.split('\n')
    .map((line) => line.trim())
    .filter((line) => line.includes('bump_version_manifests'))
    .filter((line) => !line.startsWith('#') && !line.startsWith('bump_version_manifests()'));
}

const OLD = '0.0.17';
const NEW = '0.0.20';

const tempDirs: string[] = [];
afterEach(() => {
  while (tempDirs.length) rmSync(tempDirs.pop()!, { recursive: true, force: true });
});

function cargoLock(desktopVersion: string, opts: { withDecoy?: boolean } = {}): string {
  const decoy = opts.withDecoy
    ? `[[package]]\nname = "some-dependency"\nversion = "${OLD}"\ndependencies = []\n\n`
    : '';
  return (
    `# This file is automatically @generated by Cargo.\nversion = 3\n\n` +
    decoy +
    `[[package]]\nname = "papercusp-desktop"\nversion = "${desktopVersion}"\ndependencies = [\n "bytes",\n]\n`
  );
}

/** A throwaway papercusp-desktop-shaped checkout at version OLD. */
function makeCheckout(opts: { withDecoy?: boolean; lock?: string | null } = {}): string {
  const dir = mkdtempSync(join(tmpdir(), 'relcut-writeback-'));
  tempDirs.push(dir);
  mkdirSync(join(dir, 'src-tauri'), { recursive: true });
  writeFileSync(join(dir, 'package.json'), `${JSON.stringify({ name: 'papercusp-desktop', version: OLD, private: true }, null, 2)}\n`);
  writeFileSync(join(dir, 'src-tauri', 'tauri.conf.json'), `${JSON.stringify({ productName: 'Papercusp', version: OLD, identifier: 'ai.papercusp' }, null, 2)}\n`);
  writeFileSync(join(dir, 'src-tauri', 'Cargo.toml'), `[package]\nname = "papercusp-desktop"\nversion = "${OLD}"\nedition = "2021"\n\n[dependencies]\nbytes = "1"\n`);
  const lock = opts.lock === undefined ? cargoLock(OLD, opts) : opts.lock;
  if (lock !== null) writeFileSync(join(dir, 'src-tauri', 'Cargo.lock'), lock);
  return dir;
}

function runBump(checkout: string, withLock: boolean): { status: number; stderr: string } {
  const argv = withLock ? `"${checkout}" with-lock` : `"${checkout}"`;
  const res = spawnSync('bash', ['-c', `set -euo pipefail\nVERSION="${NEW}"\n${helperSource()}\nbump_version_manifests ${argv}`], {
    encoding: 'utf8',
  });
  return { status: res.status ?? -1, stderr: res.stderr ?? '' };
}

const readJsonVersion = (p: string): unknown => (JSON.parse(readFileSync(p, 'utf8')) as Record<string, unknown>).version;

describe('bump_version_manifests (extracted from release-local.sh)', () => {
  it('rewrites the three manifests', () => {
    const dir = makeCheckout();
    expect(runBump(dir, false).status).toBe(0);
    expect(readJsonVersion(join(dir, 'package.json'))).toBe(NEW);
    expect(readJsonVersion(join(dir, 'src-tauri', 'tauri.conf.json'))).toBe(NEW);
    expect(readFileSync(join(dir, 'src-tauri', 'Cargo.toml'), 'utf8')).toContain(`version = "${NEW}"`);
  });

  // LOAD-BEARING: release:cut's reuseSeed residue validator accepts ONLY the three paths in
  // RELEASE_RESUME_VERSION_PATHS as cutter-owned dirt. If the WORKTREE bump ever starts
  // writing Cargo.lock too, every reuseSeed retry refuses the very root it must resume with
  // "non-cutter path: src-tauri/Cargo.lock". The canonical writeback passes with-lock
  // precisely because nothing regenerates the lock over there.
  it('does NOT touch Cargo.lock without with-lock', () => {
    const dir = makeCheckout();
    const before = readFileSync(join(dir, 'src-tauri', 'Cargo.lock'), 'utf8');
    expect(runBump(dir, false).status).toBe(0);
    expect(readFileSync(join(dir, 'src-tauri', 'Cargo.lock'), 'utf8')).toBe(before);
    expect(before).toContain(`version = "${OLD}"`);
  });

  it('rewrites Cargo.lock with with-lock', () => {
    const dir = makeCheckout();
    expect(runBump(dir, true).status).toBe(0);
    expect(readFileSync(join(dir, 'src-tauri', 'Cargo.lock'), 'utf8')).toContain(
      `name = "papercusp-desktop"\nversion = "${NEW}"`,
    );
  });

  it('anchors on the package NAME, leaving a same-version dependency alone', () => {
    const dir = makeCheckout({ withDecoy: true });
    expect(runBump(dir, true).status).toBe(0);
    const lock = readFileSync(join(dir, 'src-tauri', 'Cargo.lock'), 'utf8');
    expect(lock).toContain(`name = "some-dependency"\nversion = "${OLD}"`);
    expect(lock).toContain(`name = "papercusp-desktop"\nversion = "${NEW}"`);
  });

  // The can-falsely-pass case: if the lock format moves and the anchor stops matching, the
  // rewrite must FAIL rather than report success having changed nothing.
  it('FAILS when the papercusp-desktop lock entry is absent', () => {
    const dir = makeCheckout({ lock: `# @generated\nversion = 3\n\n[[package]]\nname = "only-a-dependency"\nversion = "1.0.0"\n` });
    const res = runBump(dir, true);
    expect(res.status).not.toBe(0);
    expect(res.stderr).toContain('papercusp-desktop package entry');
  });

  // The agreement that keeps reuseSeed working: the bash rewrite and cut.ts's own
  // expectedVersionFile() must produce byte-identical output. They are separate
  // implementations of one contract, so nothing but a test holds them together.
  it('produces residue that cut.ts still recognises as cutter-owned', () => {
    const dir = makeCheckout();
    const head = Object.fromEntries(
      RELEASE_RESUME_VERSION_PATHS.map((p) => [p, readFileSync(join(dir, p), 'utf8')]),
    );
    expect(runBump(dir, false).status).toBe(0);

    const verdict = validateReleaseResumeResidue({
      superprojectStatus: ' m papercusp-desktop',
      desktopStatus: RELEASE_RESUME_VERSION_PATHS.map((p) => ` M ${p}`).join('\n'),
      version: NEW,
      files: Object.fromEntries(
        RELEASE_RESUME_VERSION_PATHS.map((p) => [p, { head: head[p]!, worktree: readFileSync(join(dir, p), 'utf8') }]),
      ),
    });
    expect(verdict).toEqual({ ok: true });
  });

  it('recognises a package manifest bump without canonicalising escaped JSON literals', () => {
    const head = '{\n  "name": "papercusp-desktop",\n  "version": "0.0.17",\n  "scripts": {\n    "check": "echo \'\\u2713 ready\'"\n  }\n}\n';
    const worktree = head.replace('"0.0.17"', '"0.0.20"');
    expect(validateReleaseResumeResidue({
      superprojectStatus: ' M papercusp-desktop',
      desktopStatus: ' M package.json',
      desktopHeadMatches: true,
      version: '0.0.20',
      files: { 'package.json': { head, worktree } },
    })).toEqual({ ok: true });
  });
});

// The call SITES, not the helper's behaviour. Every test above picks the arity itself via
// runBump(), so all of them keep passing if the worktree call starts passing with-lock. The two
// directions are protected asymmetrically: DROPPING with-lock from the canonical call is caught
// loudly on every cut by that call's own post-write verifier, while ADDING it to the worktree
// call is caught only by validateReleaseResumeResidue, and only on a reuseSeed resume — so it
// stays latent until a retry refuses the very root it meant to resume.
describe('bump_version_manifests call sites in release-local.sh', () => {
  it('invokes the helper exactly twice', () => {
    expect(callSites()).toHaveLength(2);
  });

  it('calls the cut WORKTREE without with-lock', () => {
    const worktree = callSites().filter((line) => line.includes('"$ROOT"'));
    expect(worktree, 'expected exactly one bump_version_manifests "$ROOT" call').toHaveLength(1);
    expect(worktree[0]).not.toContain('with-lock');
  });

  it('calls the CANONICAL checkout with with-lock', () => {
    const canonical = callSites().filter((line) => line.includes('"$_canon"'));
    expect(canonical, 'expected exactly one bump_version_manifests "$_canon" call').toHaveLength(1);
    expect(canonical[0]).toContain('with-lock');
  });
});

describe('buildCutEnv canonical root plumbing', () => {
  const base = { ownerName: 'Avi' };

  it('passes the canonical desktop root to the cutter', () => {
    const env = buildCutEnv({}, 'a'.repeat(40), { ...base, canonicalDesktopRoot: '/repo/papercusp-desktop' });
    expect(env.PAPERCUSP_RELEASE_CANONICAL_DESKTOP_ROOT).toBe('/repo/papercusp-desktop');
  });

  // Absent => release-local.sh skips the writeback rather than guessing a path.
  it('omits the variable when no canonical root is supplied', () => {
    const env = buildCutEnv({}, 'a'.repeat(40), base);
    expect(env).not.toHaveProperty('PAPERCUSP_RELEASE_CANONICAL_DESKTOP_ROOT');
  });

  it('keeps LOCAL-only enforcement intact', () => {
    const env = buildCutEnv({}, 'a'.repeat(40), { ...base, canonicalDesktopRoot: '/repo/papercusp-desktop' });
    expect(env.PAPERCUSP_PUBLISH_GITHUB).toBe('0');
  });
});
