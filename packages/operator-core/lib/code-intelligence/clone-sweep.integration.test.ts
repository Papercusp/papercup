import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import type postgres from 'postgres';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createFreshPgDb, applyEventSubstrateMigrationsForTest, type FreshPgDb } from '../../test/_pg-helpers';
import { HARNESS_FEATURES_CONSOLIDATED_DDL, WORK_ITEM_DEPS_DDL } from '../../test/_work-items-schema';
import { ensureCoordCapabilityTables } from '@papercusp/coordination/capabilities';
import { buildCloneIndex } from './clone-index';

const WS = 'clone-sweep-test', H = 'papercup';
const h = vi.hoisted(() => ({ sql: undefined as unknown as postgres.Sql }));
vi.mock('@papercusp/db-org', async orig => ({ ...(await orig<Record<string, unknown>>()), getOrgPg: () => ({ sql: h.sql }) }));
vi.mock('../agent-tools/coordination/log', async orig => ({ ...(await orig<Record<string, unknown>>()), coordScopeWorkspace: () => WS }));
vi.mock('../pot-membership', async orig => ({ ...(await orig<Record<string, unknown>>()),
  resolveWorkItemPot: async ({ rawSlug }: { rawSlug?: string }) => rawSlug ?? null }));
vi.mock('../modes/goal-context', async orig => ({ ...(await orig<Record<string, unknown>>()), resolveGoalContext: async () => null }));

const { cloneFamilyConditionKey, cloneSweepInputSchema, fileCloneSweep, rankCloneSweep } = await import('./clone-sweep');
const { runCloneFamilySweepAction, CLONE_FAMILY_SWEEP_ACTION } = await import('../harness/routines/clone-family-sweep-action');
const { getSystemActionEntry } = await import('../harness/routines/system-actions');
let db: FreshPgDb;
const dirs: string[] = [];
const source = (name = 'sum') => `export function ${name}(xs: number[]) { let total = 0; for (const x of xs) {
  if (x > 0) { total += x; } else { total -= x; } } return total; }`;
const empty = { acceptances: [], genericEvidence: [] };
const indexFor = (tag: string, paths = [`packages/${tag}/a.ts`, `apps/${tag}/b.ts`]) =>
  buildCloneIndex(paths.map((path, n) => ({ path, source: source(`sum${n}`) })), { minMass: 8 });
const scope = (fireId: string) => ({ workspaceId: WS, harness: H, fireId });
const countKey = async (key: string) => {
  const rows = await db.sql`SELECT feature_id FROM harness_shared.work_items
    WHERE workspace_id = ${WS} AND payload -> '_conditionUpsert' ->> 'conditionKey' = ${key}`;
  return rows.map(r => r.feature_id);
};

beforeAll(async () => {
  db = await createFreshPgDb('clone-sweep'); h.sql = db.sql;
  const sqlDir = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../libs/papercusp/libs/db/sql');
  await db.sql.unsafe(HARNESS_FEATURES_CONSOLIDATED_DDL);
  await db.sql.unsafe('ALTER TABLE harness_shared.work_items ADD COLUMN IF NOT EXISTS first_claimed_at timestamptz');
  await db.sql.unsafe(readFileSync(join(sqlDir, '1219-blueprint-operation-invocations.sql'), 'utf8')).simple();
  await db.sql.unsafe(WORK_ITEM_DEPS_DDL).simple();
  await ensureCoordCapabilityTables(db.sql);
  await db.sql.unsafe(`CREATE TABLE IF NOT EXISTS harness_shared.coord_event_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id text NOT NULL DEFAULT 'default',
    surface text NOT NULL, writer_key text, msg_id text NOT NULL, body jsonb NOT NULL, harness_slug text, ts timestamptz NOT NULL DEFAULT now())`);
  await db.sql.unsafe(`ALTER TABLE harness_shared.work_items ADD COLUMN IF NOT EXISTS assignee_rank integer,
    ADD COLUMN IF NOT EXISTS rank_writer text, ADD COLUMN IF NOT EXISTS rank_updated_at timestamptz`);
  await applyEventSubstrateMigrationsForTest(db.sql, { label: 'clone-sweep.integration', extra: [
    '741-work-items-condition-key-singleton.sql', '777-work-items-embedding-recipe-discriminator.sql',
    '1110-work-items-admission-flags-generated-columns.sql', '1135-work-items-epoch-ms-timestamp-guard.sql',
    '1194-work-items-directive-ref.sql', '1294-work-item-readiness-payload-projections.sql', '1308-work-items-severity-projection.sql',
    '1534-work-items-duplicate-of.sql',
  ] });
}, 120000);
afterAll(async () => { for (const dir of dirs) rmSync(dir, { recursive: true, force: true }); await db?.cleanup(); });

describe('durable clone sweep', () => {
  it('REUSE-P-008-01 files once across simultaneous, repeated, restarted and terminal-history sweeps', async () => {
    const ranked = rankCloneSweep(indexFor('once'), empty);
    expect(ranked).toHaveLength(1);
    const runs = await Promise.all(Array.from({ length: 4 }, (_, n) => fileCloneSweep(ranked, scope(`fire-${n}`))));
    expect(runs.reduce((n, run) => n + run.created, 0)).toBe(1);
    const ids = await countKey(cloneFamilyConditionKey(ranked[0].family));
    expect(ids).toHaveLength(1);
    const restarted = await fileCloneSweep(rankCloneSweep(indexFor('once'), empty), scope('restart'));
    expect(restarted.rows[0]).toMatchObject({ disposition: 'reused', itemId: ids[0] });
    // The lifecycle clears condition_key, retaining the original upsert marker.
    await db.sql`UPDATE harness_shared.work_items SET status = 'done', condition_key = NULL WHERE feature_id = ${ids[0]}`;
    const terminal = await fileCloneSweep(ranked, scope('after-terminal'));
    expect(terminal.rows[0]).toMatchObject({ disposition: 'reused', itemId: ids[0] });
    expect(await countKey(cloneFamilyConditionKey(ranked[0].family))).toEqual(ids);
    const [item] = await db.sql`SELECT status FROM harness_shared.work_items WHERE feature_id = ${ids[0]}`;
    expect(item.status).toBe('done');
  }, 60000);

  it('keeps vendor copies for derive-and-sync, removes tests/retired copies, and ranks redundant mass', async () => {
    const index = indexFor('vendor', ['templates/example/a.ts', 'packages/live/b.ts', 'packages/live/c.test.ts', '_retired/a.ts']);
    const ranked = rankCloneSweep(index, empty);
    expect(ranked).toHaveLength(1);
    expect(ranked[0]).toMatchObject({ copies: 2, disposition: 'derive-and-sync', generic: false });
    const out = await fileCloneSweep(ranked, { ...scope('vendor'), workspaceId: 'clone-vendor-test' });
    const [item] = await db.sql`SELECT payload, summary FROM harness_shared.work_items WHERE feature_id = ${out.rows[0].itemId}`;
    expect(item.payload.cloneFamily.disposition).toBe('derive-and-sync');
    expect(item.summary).toContain('templates/example/a.ts');
    expect(item.summary).not.toContain('c.test.ts');
    expect(ranked[0].redundantMass).toBe(ranked[0].family.members[0].mass);
    index.update({ path: 'apps/third/c.ts', source: source('third') });
    const three = rankCloneSweep(index, empty)[0];
    expect(three.copies).toBe(3);
    expect(three.redundantMass).toBe(2 * ranked[0].redundantMass);
    expect(three.packageDistance).toBeGreaterThan(0);
  });

  it('expires intentional acceptance and invalidates changed membership or normalization; reviewed generic evidence is exact', async () => {
    const index = indexFor('accept'), initial = rankCloneSweep(index, empty)[0];
    const review = { familyId: initial.family.id, membersDigest: initial.membersDigest, reason: 'reviewed intentional copies' };
    const input = { acceptances: [{ ...review, expiresAt: '2030-01-01T00:00:00Z' }], genericEvidence: [review] };
    const accepted = rankCloneSweep(index, input, new Date('2026-10-23T00:00:00Z'));
    expect(accepted[0]).toMatchObject({ accepted: true, generic: true });
    expect((await fileCloneSweep(accepted, scope('accepted'))).rows[0].disposition).toBe('accepted');
    expect(rankCloneSweep(index, input, new Date('2031-01-01T00:00:00Z'))[0].accepted).toBe(false);
    index.update({ path: 'apps/accept/c.ts', source: source('third') });
    const merged = rankCloneSweep(index, input, new Date('2026-10-23T00:00:00Z'))[0];
    expect(merged.family.id).toBe(initial.family.id);
    expect(merged).toMatchObject({ accepted: false, generic: false, copies: 3 });
    index.update({ path: 'apps/accept/c.ts', source: 'export function third() { return true; }' });
    const split = rankCloneSweep(index, input, new Date('2026-10-23T00:00:00Z'))[0];
    expect(split.family.id).toBe(initial.family.id);
    expect(split.accepted).toBe(true);
    expect(rankCloneSweep(index, { ...input, acceptances: [{ ...input.acceptances[0], familyId: 'old-normalizer' }] })[0].accepted).toBe(false);
    const expired = await fileCloneSweep(rankCloneSweep(index, input, new Date('2031-01-01T00:00:00Z')), scope('expired'));
    expect(expired.rows[0].itemId).toBeTruthy();
  });

  it('registers the exact schedulable action and dispatches a ledgered bounded child, skipping overlap', async () => {
    expect(getSystemActionEntry(CLONE_FAMILY_SWEEP_ACTION)?.planSchedulable).toBe(true);
    const root = mkdtempSync(join(tmpdir(), 'clone-sweep-action-')); dirs.push(root);
    mkdirSync(join(root, 'scripts'), { recursive: true }); mkdirSync(join(root, 'node_modules/tsx/dist'), { recursive: true });
    writeFileSync(join(root, 'scripts/clone-family-sweep.mts'), ''); writeFileSync(join(root, 'node_modules/tsx/dist/loader.mjs'), '');
    const spawn = vi.fn(async (_cmd, _args, _spec, options) => ({ taskId: options.taskId, confined: true, scopeUnit: 'test.scope' }));
    const ctx = { installSlug: H, workspaceId: WS, routineId: 'routine-test', workflowId: 'fire-test',
      triggerConfig: {}, payloadTemplate: { input: { root } } };
    const result = await runCloneFamilySweepAction(ctx, { spawn: spawn as never, logDir: join(root, 'logs'), inFlight: async () => [] });
    expect(result.diagnostics).toMatchObject({ status: 'launched', fireId: 'fire-test', confined: true });
    const call = spawn.mock.calls[0];
    expect(call[2]).toMatchObject({ launchedBy: 'system:clone-family-sweep', runtimeMaxSec: 900, memoryMaxBytes: 4 * 1024 ** 3 });
    expect(call[3]).toMatchObject({ requireRegistration: true, workspaceId: WS });
    expect(JSON.parse(readFileSync(String(result.diagnostics!.configPath), 'utf8'))).toMatchObject({ workspaceId: WS, harness: H, input: { root } });
    const overlap = await runCloneFamilySweepAction(ctx, { spawn: spawn as never, inFlight: async () => [{ taskId: 'existing' }] });
    expect(overlap.diagnostics).toEqual({ status: 'skipped-overlap', taskIds: ['existing'] });
    expect(spawn).toHaveBeenCalledTimes(1);
    expect(() => cloneSweepInputSchema.parse({ root, acceptances: [{ familyId: 'a', membersDigest: 'b', reason: '', expiresAt: 'tomorrow' }] })).toThrow();
  });
});
