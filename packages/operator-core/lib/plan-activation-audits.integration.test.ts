/**
 * Migration 938 + activation-audit store contract against a real Postgres.
 *
 * Completion and activation are two typed passes in ONE append-only ledger. The
 * regression target is the seam between the additive migration and
 * `recordPlanAudit`: old completion rows must keep their meaning, activation rows
 * must carry an exact revision anchor, and each reader must select its own kind.
 */
