async function seedPostEpochPlan(content = postEpochContent, slug = 'post-epoch-seed-target') {
  const contentHash = hashPlanContent(content);
  await db.sql`
    INSERT INTO harness_shared.harness_plans
      (workspace_id, harness_slug, plan_slug, title, status, content, content_hash, version)
    VALUES ('activation-audit-test', 'papercusp', ${slug}, 'Post-epoch seed target', 'draft', ${content}, ${contentHash}, 7)`;
  for (const [seq, itemId] of ['P-001', 'P-002'].entries()) {
    await db.sql`
      INSERT INTO harness_shared.plan_items
        (workspace_id, harness_slug, plan_slug, item_id, seq, status, item_text)
      VALUES ('activation-audit-test', 'papercusp', ${slug}, ${itemId}, ${seq + 1},
              ${itemId === 'P-001' ? 'todo' : 'blocked'}, ${`work for ${itemId}`})`;
  }
  const revisions = await db.sql<Array<{ id: number | string }>>`
    INSERT INTO harness_shared.plan_revisions
      (workspace_id, harness_slug, plan_slug, seq, content_hash, content_snapshot)
    VALUES ('activation-audit-test', 'papercusp', ${slug}, 7, ${contentHash}, ${content})
    RETURNING id`;
  return { id: Number(revisions[0]?.id), contentHash };
}

