const payload = {
  sourceRanges: [{ sourceKind: 'codex', sessionId: 'session-full-id', fromTurn: 3, toTurn: 17 }],
  mappings: [{
    id: 'M-001',
    sourceRefs: ['session_turn:codex:session-full-id:7'],
    requirement: 'activation requires a complete conversation audit',
    planTargets: ['P-004', 'D-001'],
    disposition: 'covered' as const,
  }],
  repairedOmissions: [],
  rejectedOrSuperseded: [],
  unresolvedBlockers: [],
};

const planContent = `---
title: Activation target
slug: activation-target
status: draft
created: 2026-08-24
updated: 2026-08-24
---

# Activation target

## Requirements

- **P-001** \`todo\` enforce the activation audit

## Decisions

### D-001 — One gate

Every activation path uses the same gate.
`;

const atomicPayload = {
  ...payload,
  mappings: [{
    ...payload.mappings[0],
    planTargets: ['P-001', 'D-001', 'section:Requirements'],
  }],
};

async function seedCurrentPlan() {
  const contentHash = hashPlanContent(planContent);
  await db.sql`
    INSERT INTO harness_shared.harness_plans
      (workspace_id, harness_slug, plan_slug, content, content_hash, template)
    VALUES ('activation-audit-test', 'papercusp', 'activation-target', ${planContent}, ${contentHash}, 'rubric')`;
  const rows = await db.sql<Array<{ id: number | string }>>`
    INSERT INTO harness_shared.plan_revisions
      (workspace_id, harness_slug, plan_slug, seq, content_hash, content_snapshot)
    VALUES ('activation-audit-test', 'papercusp', 'activation-target', 9, ${contentHash}, ${planContent})
    RETURNING id`;
  return { id: Number(rows[0]?.id), contentHash };
}

const postEpochContent = `---
title: Post-epoch seed target
slug: post-epoch-seed-target
status: draft
created: 2026-09-04
updated: 2026-09-04
---

# Post-epoch seed target

## Requirements

**R-1 — Persist the canonical promise.** One acceptance criterion remains the BAR authority.

**R-2 — Expose current runtime truth.** Live evidence reports the current result.

## Design

### Bar-to-work map for this plan

| bar | implementing plan items | evidence plane |
|---|---|---|
| R-1 | P-001 | tree |
| R-2 | P-001, P-002 | live |

## Phase 1 — Build

- **P-001** \`todo\` persist the BAR
- **P-002** \`blocked\` expose live truth
`;

async function seedPostEpochPlan(content = postEpochContent, slug = 'post-epoch-seed-target') {
  const contentHash = hashPlanContent(content);
  await db.sql`
    INSERT INTO harness_shared.harness_plans
      (workspace_id, harness_slug, plan_slug, title, status, content, content_hash, version)
    VALUES ('activation-audit-test', 'papercusp', ${slug}, 'Post-epoch seed target', 'draft', ${content}, ${contentHash}, 7)`;
  for (const [seq, itemId] of ['P-001', 'P-002'].entries()) {
    await db.sql`
      INSERT INTO harness_shared.plan_items
        (workspace_id, harness_slug, plan_slug, item_id, seq, status, item_text)
      VALUES ('activation-audit-test', 'papercusp', ${slug}, ${itemId}, ${seq + 1},
              ${itemId === 'P-001' ? 'todo' : 'blocked'}, ${`work for ${itemId}`})`;
  }
  const revisions = await db.sql<Array<{ id: number | string }>>`
    INSERT INTO harness_shared.plan_revisions
      (workspace_id, harness_slug, plan_slug, seq, content_hash, content_snapshot)
    VALUES ('activation-audit-test', 'papercusp', ${slug}, 7, ${contentHash}, ${content})
    RETURNING id`;
  return { id: Number(revisions[0]?.id), contentHash };
}

describe('migration 938 activation-audit ledger', () => {
  it('returns the claimable repair lane when low-level validation rejects open coverage', async () => {
    const result = await recordCurrentActivationAudit({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'activation-target',
      createdBy: 'su-test',
      activation: {
        ...payload,
        unresolvedBlockers: ['map the owner constraint before activation'],
      },
    });

    expect(result).toMatchObject({
      ok: false,
      error: 'activation_blocked',
      repairWorkItem: 'EI-ACTIVATION-REPAIR',
      repairFiling,
    });
    const repairCall = vi.mocked(ensureActivationAuditRepairFiling).mock.calls[0]?.[0];
    expect(repairCall).toMatchObject({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'activation-target',
    });
    // The control that makes the close CONDITIONAL rather than a sweep: a refused
    // activation must never reconcile the very filing it just raised.
    expect(reconcileActivationAuditRepairFiling).not.toHaveBeenCalled();
  });

  it('preserves completion defaults and reads each audit kind independently', async () => {
    const completion = await recordPlanAudit({
      planSlug: 'audited-plan',
      harnessSlug: 'papercusp',
      createdBy: 'su-test',
      auditedSha: 'completion-head',
      items: [],
    });
    const activation = await recordPlanAudit({
      auditKind: 'activation',
      planSlug: 'audited-plan',
      harnessSlug: 'papercusp',
      createdBy: 'su-test',
      activation: payload,
      auditedPlanRevision: { id: 41, seq: 6, contentHash: 'a'.repeat(64) },
    });

    expect(completion).toMatchObject({ auditKind: 'completion', auditSeq: 1, activation: null });
    expect(activation).toMatchObject({
      auditKind: 'activation',
      auditSeq: 2,
      activation: payload,
      auditedPlanRevision: { id: 41, seq: 6, contentHash: 'a'.repeat(64) },
      items: [],
      findings: [],
    });
    await expect(db.sql`
      SELECT audit_kind,
             jsonb_typeof(activation) AS activation_type,
             jsonb_typeof(items) AS items_type,
             jsonb_typeof(findings) AS findings_type
        FROM harness_shared.plan_audits
       ORDER BY audit_seq
    `).resolves.toEqual([
      { audit_kind: 'completion', activation_type: null, items_type: 'array', findings_type: 'array' },
      { audit_kind: 'activation', activation_type: 'object', items_type: 'array', findings_type: 'array' },
    ]);
    await expect(getLatestPlanAudit('audited-plan')).resolves.toMatchObject({
      auditKind: 'completion',
      auditSeq: 1,
    });
    await expect(getLatestActivationAudit('audited-plan')).resolves.toMatchObject({
      auditKind: 'activation',
      auditSeq: 2,
    });
  });

  it('rejects an activation-shaped row without its exact revision anchor', async () => {
    await expect(db.sql`
      INSERT INTO harness_shared.plan_audits
        (workspace_id, harness_slug, plan_slug, audit_seq, created_by, audit_kind, activation)
      VALUES
        ('activation-audit-test', 'papercusp', 'invalid-plan', 1, 'su-test', 'activation', ${JSON.stringify(payload)}::text::jsonb)
    `).rejects.toThrow(/plan_audits_activation_shape_check/);
  });

  it('atomically validates plan targets and records the exact current revision', async () => {
    const revision = await seedCurrentPlan();

    const result = await recordCurrentActivationAudit({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'activation-target',
      createdBy: 'su-test',
      activation: atomicPayload,
    });

    expect(result).toMatchObject({
      ok: true,
      auditedPlanRevision: { id: revision.id, seq: 9, contentHash: revision.contentHash },
      audit: { auditKind: 'activation', auditedPlanRevision: { id: revision.id, seq: 9 } },
      repairReconciliation,
    });
    // A clean audit is the EVENT that clears the repair condition, so the close
    // fires from here — with the audit_seq that cleared it as its evidence.
    // Without this leg the filing outlives its condition until an agent notices
    // by hand (EI-22090432802240306: 0 of 13 filings were ever machine-closed).
    expect(reconcileActivationAuditRepairFiling).toHaveBeenCalledTimes(1);
    expect(vi.mocked(reconcileActivationAuditRepairFiling).mock.calls[0]?.[0]).toEqual({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'activation-target',
      auditSeq: 1,
    });
  });

  it('rejects a mapping target absent from the locked current revision', async () => {
    await seedCurrentPlan();

    const result = await recordCurrentActivationAudit({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'activation-target',
      createdBy: 'su-test',
      activation: {
        ...atomicPayload,
        mappings: [{ ...atomicPayload.mappings[0], planTargets: ['P-999'] }],
      },
    });

    expect(result).toMatchObject({
      ok: false,
      error: 'plan_targets_invalid',
      problems: [expect.objectContaining({ mappingId: 'M-001', target: 'P-999', code: 'unknown_item' })],
    });
    await expect(db.sql`SELECT 1 FROM harness_shared.plan_audits`).resolves.toEqual([]);
  });

  it('seeds rubric, BAR map projections, plan pin, and audit in one post-epoch transaction', async () => {
    const revision = await seedPostEpochPlan();
    const activation = {
      ...payload,
      mappings: [{ ...payload.mappings[0], planTargets: ['P-001', 'P-002', 'section:Requirements'] }],
    };

    const first = await recordCurrentActivationAudit({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'post-epoch-seed-target',
      createdBy: 'su-seeder',
      activation,
    });

    expect(first).toMatchObject({
      ok: true,
      auditedPlanRevision: { id: revision.id, seq: 7, contentHash: revision.contentHash },
      barSeed: {
        rubricSlug: 'acceptance-post-epoch-seed-target',
        rubricRevision: 1,
        bars: 2,
        projectionEdges: 3,
        rubricChanged: true,
      },
    });
    const subjects = await db.sql<Array<Record<string, unknown>>>`
      SELECT acceptance_bar_epoch, acceptance_bar_cohort, acceptance_bar_set_hash,
             acceptance_bar_rubric_slug, acceptance_bar_rubric_revision, acceptance_bar_seeded_by
        FROM harness_shared.harness_plans
       WHERE plan_slug = 'post-epoch-seed-target'`;
    expect(subjects[0]).toMatchObject({
      acceptance_bar_epoch: 1,
      acceptance_bar_cohort: 'post-epoch',
      acceptance_bar_set_hash: expect.stringMatching(/^[a-f0-9]{64}$/),
      acceptance_bar_rubric_slug: 'acceptance-post-epoch-seed-target',
      acceptance_bar_rubric_revision: 1,
      acceptance_bar_seeded_by: 'su-seeder',
    });
    const rubricRows = await db.sql<Array<{ template_data: Record<string, unknown>; version: string | number }>>`
      SELECT template_data, version
        FROM harness_shared.harness_plans
       WHERE plan_slug = 'acceptance-post-epoch-seed-target'`;
    expect(rubricRows).toHaveLength(1);
    expect(rubricRows[0]?.template_data).toMatchObject({
      kind: 'acceptance',
      subjectPlan: 'post-epoch-seed-target',
      barSetHash: subjects[0]?.acceptance_bar_set_hash,
      criteria: [
        expect.objectContaining({ barKey: 'R-1', evidencePlane: 'tree', mandatory: true }),
        expect.objectContaining({ barKey: 'R-2', evidencePlane: 'live', mandatory: true }),
      ],
    });
    const clauses = await db.sql<Array<Record<string, unknown>>>`
      SELECT spec_id, current_revision, source_bar_key, source_bar_hash,
             source_bar_set_hash, source_rubric_slug, source_rubric_revision, evidence_plane
        FROM harness_shared.plan_spec_clauses c
        JOIN harness_shared.plan_spec_clause_revisions r
          USING (workspace_id, harness_slug, plan_slug, spec_id)
       WHERE c.plan_slug = 'post-epoch-seed-target'
         AND r.revision = c.current_revision
       ORDER BY spec_id`;
    expect(clauses).toHaveLength(3);
    expect(clauses).toEqual(expect.arrayContaining([
      expect.objectContaining({
        spec_id: 'AUTO-BAR-R-2-P-002',
        source_bar_key: 'R-2',
        source_bar_set_hash: subjects[0]?.acceptance_bar_set_hash,
        source_rubric_slug: 'acceptance-post-epoch-seed-target',
        source_rubric_revision: 1,
        evidence_plane: 'live',
      }),
    ]));

    const second = await recordCurrentActivationAudit({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'post-epoch-seed-target',
      createdBy: 'su-seeder',
      activation,
    });
    expect(second).toMatchObject({ ok: true, barSeed: { rubricChanged: false, rubricRevision: 1 } });
    await expect(db.sql`
      SELECT count(*)::int AS n, max(current_revision)::int AS max_revision
        FROM harness_shared.plan_spec_clauses
       WHERE plan_slug = 'post-epoch-seed-target'
    `).resolves.toEqual([{ n: 3, max_revision: 1 }]);
  });

  it('re-audits an amended pinned revision without reverting its canonical BAR or METHOD', async () => {
    await seedPostEpochPlan();
    const input = {
      workspaceId: 'activation-audit-test', harnessSlug: 'papercusp',
      planSlug: 'post-epoch-seed-target', createdBy: 'su-seeder',
      activation: { ...payload, mappings: [{ ...payload.mappings[0],
        planTargets: ['P-001', 'P-002', 'section:Requirements'] }] },
    };
    expect(await recordCurrentActivationAudit(input)).toMatchObject({ ok: true });
    const [stored] = await db.sql<Array<{ template_data: unknown }>>`
      SELECT template_data FROM harness_shared.harness_plans
       WHERE plan_slug = 'acceptance-post-epoch-seed-target'`;
    // Persist the post-amendment state as a fixture; amendment authorization has
    // its own real-PG suite. The old Requirements text deliberately stays intact.
    const amended = rubricTemplateDataSchema.parse(stored!.template_data);
    amended.criteria = amended.criteria.map((criterion) => criterion.barKey !== 'R-1' ? criterion :
      normalizeAcceptanceBarCriterion({ ...criterion, barHash: undefined,
        driftMarkers: 'The runtime returns a different committed BAR revision.',
        evidencePlane: 'live', requiredScope: ['live'],
        method: 'Read the committed runtime BAR revision.',
        check: { kind: 'instrument', instrumentKey: 'none' },
      }));
    amended.barSetHash = computeAcceptanceBarSetHash(amended.criteria);
    await db.sql`UPDATE harness_shared.harness_plans SET
      template_data = ${JSON.stringify(amended)}::text::jsonb, version = 2
      WHERE plan_slug = 'acceptance-post-epoch-seed-target'`;
    await db.sql`UPDATE harness_shared.harness_plans SET status = 'active',
      acceptance_bar_set_hash = ${amended.barSetHash}, acceptance_bar_rubric_revision = 2
      WHERE plan_slug = 'post-epoch-seed-target'`;

    const reaudit = await recordCurrentActivationAudit({ ...input, createdBy: 'su-reauditor' });
    expect(reaudit, JSON.stringify(reaudit))
      .toMatchObject({ ok: true, barSeed: { rubricRevision: 2, rubricChanged: false } });
    const [after] = await db.sql<Array<{ template_data: unknown; version: number }>>`
      SELECT template_data, version::int FROM harness_shared.harness_plans
       WHERE plan_slug = 'acceptance-post-epoch-seed-target'`;
    expect(after).toEqual({ template_data: amended, version: 2 });
    const currentProjection = () => db.sql<Array<Record<string, unknown>>>`
      SELECT r.revision, r.falsifier, r.source_bar_hash, r.evidence_plane,
             r.source_rubric_revision, r.required_evidence
        FROM harness_shared.plan_spec_clauses c
        JOIN harness_shared.plan_spec_clause_revisions r
          USING (workspace_id, harness_slug, plan_slug, spec_id)
       WHERE c.plan_slug = 'post-epoch-seed-target'
         AND c.spec_id = 'AUTO-BAR-R-1-P-001' AND r.revision = c.current_revision`;
    const projected = await currentProjection();
    expect(projected).toEqual([expect.objectContaining({
      source_bar_hash: amended.criteria[0].barHash, evidence_plane: 'live',
      required_evidence: ['live'], source_rubric_revision: 2,
      falsifier: { observation: amended.criteria[0].driftMarkers },
    })]);
    expect(await recordCurrentActivationAudit(input)).toMatchObject({ ok: true,
      barSeed: { rubricRevision: 2, rubricChanged: false } });
    expect(await currentProjection()).toEqual(projected);

    // Advancing the source revision does not grant this preservation path to a
    // direct Requirements edit: the existing started-BAR guard still refuses it.
    const changed = postEpochContent.replace('One acceptance criterion remains the BAR authority.',
      'A weaker promise replaces the canonical BAR.');
    const hash = hashPlanContent(changed);
    await db.sql`UPDATE harness_shared.harness_plans SET content = ${changed}, content_hash = ${hash}, version = 8
      WHERE plan_slug = 'post-epoch-seed-target'`;
    await db.sql`INSERT INTO harness_shared.plan_revisions
      (workspace_id, harness_slug, plan_slug, seq, content_hash, content_snapshot)
      VALUES ('activation-audit-test', 'papercusp', 'post-epoch-seed-target', 8, ${hash}, ${changed})`;
    await expect(recordCurrentActivationAudit(input)).rejects.toThrow('BAR meaning cannot change');
    const [unchanged] = await db.sql<Array<{ template_data: unknown }>>`
      SELECT template_data FROM harness_shared.harness_plans
       WHERE plan_slug = 'acceptance-post-epoch-seed-target'`;
    expect(unchanged!.template_data).toEqual(amended);
  });

  it('keeps the cohort marker but rolls back audit/rubric/projections on an incomplete map', async () => {
    const incomplete = postEpochContent.replace('| R-2 | P-001, P-002 | live |', '');
    await seedPostEpochPlan(incomplete, 'post-epoch-incomplete');
    const result = await recordCurrentActivationAudit({
      workspaceId: 'activation-audit-test',
      harnessSlug: 'papercusp',
      planSlug: 'post-epoch-incomplete',
      createdBy: 'su-seeder',
      activation: {
        ...payload,
        mappings: [{ ...payload.mappings[0], planTargets: ['P-001', 'section:Requirements'] }],
      },
    });
    expect(result).toMatchObject({ ok: false, error: 'bar_mapping_missing' });
    await expect(db.sql`
      SELECT acceptance_bar_epoch, acceptance_bar_set_hash
        FROM harness_shared.harness_plans
       WHERE plan_slug = 'post-epoch-incomplete'
    `).resolves.toEqual([{ acceptance_bar_epoch: 1, acceptance_bar_set_hash: null }]);
    await expect(db.sql`
      SELECT
        (SELECT count(*)::int FROM harness_shared.plan_audits WHERE plan_slug = 'post-epoch-incomplete') AS audits,
        (SELECT count(*)::int FROM harness_shared.harness_plans WHERE plan_slug = 'acceptance-post-epoch-incomplete') AS rubrics,
        (SELECT count(*)::int FROM harness_shared.plan_spec_clauses WHERE plan_slug = 'post-epoch-incomplete') AS clauses
    `).resolves.toEqual([{ audits: 0, rubrics: 0, clauses: 0 }]);
  });
});
