/**
 * plan-item-coverage.integration.test.ts — the PG read behind getAllPlanItemCoverage,
 * against a real Postgres (EI-13721).
 *
 * Behaviors a fake-sql unit test can't prove:
 *  - the STAMP-based coverage leg (signal 3): a work-item whose ONLY plan binding
 *    is a `payload.plan_item` stamp (no coord_links edge) still surfaces in
 *    coverage — the exact gap EI-13721 reports (WI-5150-shaped: an assignee, a
 *    stamp, zero coverage/workers). Both families (feature via
 *    harness_features_consolidated, issue via engineer_issues) and both jsonb
 *    payload shapes (real object vs postgres-js's string-scalar binding quirk —
 *    convert.integration.test.ts's documented gotcha) are covered.
 *  - dedup: a work-item that carries BOTH a coord_links edge AND a stamp is
 *    counted ONCE, not twice.
 *  - the stamp leg still joins live fleet activity (signal 2) correctly.
 *
 * classifyCoverage/compactCoverage (the pure decision logic) are covered by
 * plan-item-coverage.test.ts; getWorkItem-style resolution isn't needed here —
 * getAllPlanItemCoverage reads ids/rows straight off SQL, no work-items mock.
 */
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import postgres from 'postgres';
import { HARNESS_FEATURES_CONSOLIDATED_DDL } from '../test/_work-items-schema';
import { randomBytes } from 'node:crypto';
import { getTestPg } from '@papercusp/test-config/pg';
import { DEFAULT_COORD_WORKSPACE } from '@papercusp/coordination/event-log';
import { PLAN_ITEM_KIND, planItemRef } from './issue-blocks-merge';
import type { FleetAssignmentRow } from './fleet/assignments';

const WS = DEFAULT_COORD_WORKSPACE;

const h = vi.hoisted(() => ({ sql: undefined as unknown as postgres.Sql }));
vi.mock('@papercusp/db-org', async () => {
  const actual = await vi.importActual<typeof import('@papercusp/db-org')>('@papercusp/db-org');
  return { ...actual, getOrgPg: () => ({ sql: h.sql }) };
});
vi.mock('./workspace-registry', () => ({ activeWorkspaceId: () => WS }));

const h2 = vi.hoisted(() => ({
  rows: [] as Partial<FleetAssignmentRow>[],
}));
vi.mock('./fleet/assignments', async () => {
  const actual = await vi.importActual<typeof import('./fleet/assignments')>('./fleet/assignments');
  return {
    ...actual,
    listFleetAssignments: vi.fn(async () => h2.rows as FleetAssignmentRow[]),
  };
});

const { getAllPlanItemCoverage } = await import('./plan-item-coverage');
const { STAMP_ONLY_REL } = await import('./plan-item-coverage');

let rootSql: postgres.Sql;

beforeAll(async () => {
  const adminUri = await getTestPg();
  const dbName = `plic_${randomBytes(5).toString('hex')}`;
  const admin = postgres(adminUri, { max: 1, onnotice: () => {} });
  try {
    await admin.unsafe(`CREATE DATABASE "${dbName}"`);
  } finally {
    await admin.end({ timeout: 5 });
  }
  const u = new URL(adminUri);
  u.pathname = `/${dbName}`;
  rootSql = postgres(u.toString(), { max: 1, onnotice: () => {} });
  await rootSql.unsafe(`CREATE SCHEMA harness_shared`);
  await rootSql.unsafe(`
    CREATE TABLE harness_shared.coord_links (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id text DEFAULT 'default' NOT NULL,
      src_kind text NOT NULL, src_ref text NOT NULL,
      dst_kind text NOT NULL, dst_ref text NOT NULL,
      rel text NOT NULL, created_by text,
      created_at timestamptz DEFAULT now() NOT NULL
    )`);
  // P-010 unification: work_items base + hfc/ei compat views.
  await rootSql.unsafe(HARNESS_FEATURES_CONSOLIDATED_DDL);
  h.sql = rootSql;
}, 90_000);

afterAll(async () => {
  await rootSql?.end({ timeout: 5 });
});

beforeEach(async () => {
  await rootSql`TRUNCATE harness_shared.coord_links, harness_shared.work_items`;
  h2.rows = [];
});

async function edge(o: { plan: string; item: string; srcKind?: string; srcRef: string; rel?: string }) {
  await rootSql`
    INSERT INTO harness_shared.coord_links (workspace_id, src_kind, src_ref, dst_kind, dst_ref, rel)
    VALUES (${WS}, ${o.srcKind ?? 'issue'}, ${o.srcRef}, ${PLAN_ITEM_KIND},
            ${planItemRef(o.plan, o.item)}, ${o.rel ?? 'relates'})`;
}

const stamp = (plan: string, item: string) => ({ plan_item: { plan_slug: plan, item_id: item } });

async function insertIssue(o: { id: string; state: string; plan: string; item: string; asStringScalar?: boolean }) {
  if (o.asStringScalar) {
    // The engineer_issues compat VIEW's INSTEAD OF trigger merges NEW.payload with
    // jsonb_build_object('_ei', ...) via `||` — per PG semantics, `||` on a non-object
    // jsonb value (our scalar quirk) converts BOTH sides to single-element arrays and
    // concatenates them, so routing the scalar case through the view wouldn't exercise
    // getAllPlanItemCoverage's normalizedPayloadExpr unwrap at all — it would exercise an
    // unrelated, pre-existing trigger bug that mangles a scalar payload into an array
    // (filed separately: EI-13835). Insert straight into the base table instead, which is
    // exactly what getAllPlanItemCoverage reads and is where the postgres-js
    // string-scalar binding quirk (a client binding a JS object as a jsonb-cast param)
    // actually lands undisturbed.
    await rootSql`INSERT INTO harness_shared.work_items
                    (workspace_id, harness_slug, feature_id, item_kind, status, payload, updated_ts)
                  VALUES (${WS}, 'web', ${o.id}, 'bug', ${o.state},
                          to_jsonb(${JSON.stringify(stamp(o.plan, o.item))}::text), 100)`;
    return;
  }
  await rootSql`INSERT INTO harness_shared.engineer_issues (workspace_id, issue_id, state, payload)
                VALUES (${WS}, ${o.id}, ${o.state}, ${rootSql.json(stamp(o.plan, o.item))})`;
}

async function insertFeature(o: {
  id: string;
  harness?: string;
  status: string;
  plan: string;
  item: string;
  asStringScalar?: boolean;
}) {
  const payload = o.asStringScalar
    ? rootSql`to_jsonb(${JSON.stringify(stamp(o.plan, o.item))}::text)`
    : rootSql.json(stamp(o.plan, o.item));
  await rootSql`INSERT INTO harness_shared.harness_features_consolidated
                  (harness_slug, feature_id, workspace_id, status, payload, updated_ts)
                VALUES (${o.harness ?? 'web'}, ${o.id}, ${WS}, ${o.status}, ${payload}, 100)`;
}

describe('getAllPlanItemCoverage — stamp-based coverage (PG, EI-13721)', () => {
  it('an issue-family work-item bound ONLY via payload.plan_item (no coord_links edge) still surfaces coverage', async () => {
    await insertIssue({ id: 'WI-5150', state: 'open', plan: 'p1', item: 'P-001' });

    const cov = await getAllPlanItemCoverage();
    const c = cov.get(planItemRef('p1', 'P-001'));
    expect(c).toBeDefined();
    expect(c!.links).toEqual([
      { workItemId: 'WI-5150', rel: STAMP_ONLY_REL, terminal: false, activity: 'free', holder: null },
    ]);
    // open + nobody live on it + no direct claim → unclaimed, NOT 'none' (the
    // EI-13721 bug: this used to read undefined coverage entirely).
    expect(c!.level).toBe('unclaimed');
  });

  it('a resolved/terminal stamped issue rolls up to level "complete"', async () => {
    await insertIssue({ id: 'WI-done', state: 'resolved', plan: 'p1', item: 'P-002' });
    const cov = await getAllPlanItemCoverage();
    expect(cov.get(planItemRef('p1', 'P-002'))!.level).toBe('complete');
  });

  it('a feature-family stamped work-item terminal-classifies via passed/deprecated, not resolved/closed', async () => {
    await insertFeature({ id: 'F-1', status: 'passed', plan: 'p1', item: 'P-003' });
    await insertFeature({ id: 'F-2', status: 'todo', plan: 'p1', item: 'P-004' });
    const cov = await getAllPlanItemCoverage();
    expect(cov.get(planItemRef('p1', 'P-003'))!.level).toBe('complete');
    expect(cov.get(planItemRef('p1', 'P-004'))!.level).toBe('unclaimed');
  });

  it('unwraps a jsonb STRING-SCALAR payload (postgres-js binding quirk) for both families', async () => {
    await insertIssue({ id: 'WI-scalar', state: 'open', plan: 'p1', item: 'P-005', asStringScalar: true });
    await insertFeature({ id: 'F-scalar', status: 'todo', plan: 'p1', item: 'P-006', asStringScalar: true });
    const cov = await getAllPlanItemCoverage();
    expect(cov.get(planItemRef('p1', 'P-005'))?.links.map((l) => l.workItemId)).toEqual(['WI-scalar']);
    expect(cov.get(planItemRef('p1', 'P-006'))?.links.map((l) => l.workItemId)).toEqual(['F-scalar']);
  });

  it('dedups: a work-item with BOTH a coord_links edge AND a payload stamp counts once, keeping the edge rel', async () => {
    await insertIssue({ id: 'WI-both', state: 'open', plan: 'p1', item: 'P-007' });
    await edge({ plan: 'p1', item: 'P-007', srcRef: 'WI-both', rel: 'fixes' });

    const cov = await getAllPlanItemCoverage();
    const c = cov.get(planItemRef('p1', 'P-007'))!;
    expect(c.links).toHaveLength(1);
    expect(c.links[0]).toMatchObject({ workItemId: 'WI-both', rel: 'fixes' });
  });

  it('joins live fleet activity onto a stamp-only link (signal 2 still applies to signal 3)', async () => {
    await insertIssue({ id: 'WI-live', state: 'open', plan: 'p1', item: 'P-008' });
    h2.rows = [
      {
        source: 'work_item_claim',
        workItemId: 'WI-live',
        agentId: 'su-worker',
        orphaned: false,
        stalled: false,
        holderAlive: true,
        lastProgressAt: '2026-07-19T00:00:00Z',
      },
    ];

    const cov = await getAllPlanItemCoverage();
    const c = cov.get(planItemRef('p1', 'P-008'))!;
    expect(c.level).toBe('full');
    expect(c.workers).toEqual(['su-worker']);
    expect(c.links[0]).toMatchObject({ activity: 'progressing', holder: 'su-worker' });
  });

  it('a work-item with no plan_item stamp at all contributes no coverage row', async () => {
    await rootSql`INSERT INTO harness_shared.engineer_issues (workspace_id, issue_id, state, payload)
                  VALUES (${WS}, 'WI-nostamp', 'open', ${rootSql.json({ some: 'other-data' })})`;
    const cov = await getAllPlanItemCoverage();
    expect(cov.size).toBe(0);
  });
});
