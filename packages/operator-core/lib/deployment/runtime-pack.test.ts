import { describe, it, expect } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { packRuntimeTarball } from './runtime-pack';
import { resolveRuntimeTarball } from './bootstrap-input';

describe('packRuntimeTarball', () => {
  it('packs the tree and applies the default excludes (.git / node_modules / target)', async () => {
    const root = mkdtempSync(join(tmpdir(), 'pc-pack-'));
    try {
      writeFileSync(join(root, 'package.json'), '{"name":"x"}');
      mkdirSync(join(root, 'src'));
      writeFileSync(join(root, 'src', 'index.ts'), 'export {}');
      mkdirSync(join(root, '.git'));
      writeFileSync(join(root, '.git', 'HEAD'), 'ref: x');
      mkdirSync(join(root, 'node_modules', 'dep'), { recursive: true });
      writeFileSync(join(root, 'node_modules', 'dep', 'big.js'), '//');
      mkdirSync(join(root, 'sub', 'target'), { recursive: true });
      writeFileSync(join(root, 'sub', 'target', 'bin'), 'x');
      mkdirSync(join(root, 'apps', 'operator'), { recursive: true });
      writeFileSync(join(root, 'apps', 'operator', '.env.local'), 'SECRET=1');
      // root backups/ (kopia repo) is excluded; a NESTED source dir named
      // backups/ must SURVIVE (app/settings/backups bit us live).
      mkdirSync(join(root, 'backups'), { recursive: true });
      writeFileSync(join(root, 'backups', 'snap.bin'), 'x');
      mkdirSync(join(root, 'apps', 'operator', 'app', 'backups'), { recursive: true });
      writeFileSync(join(root, 'apps', 'operator', 'app', 'backups', 'page.tsx'), 'export {}');
      // EI-370 / found-live 2026-06-12: apps/operator-vite/dist is a build
      // output regenerated by the doc build-watch while tar reads it — "file
      // shrank" aborted the pack. It must be excluded entirely (the frame
      // never imports generated build output anyway).
      mkdirSync(join(root, 'apps', 'operator-vite', 'dist', 'internal', 'docs'), { recursive: true });
      writeFileSync(join(root, 'apps', 'operator-vite', 'dist', 'internal', 'docs', 'llms-full.txt'), 'x'.repeat(64));
      // sidecar build output — found live 2026-06-09.
      mkdirSync(join(root, 'papercusp-desktop', 'src-tauri', 'sidecar'), { recursive: true });
      writeFileSync(join(root, 'papercusp-desktop', 'src-tauri', 'sidecar', 'omp'), 'x');

      const out = join(root, '..', 'pc-pack-out.tgz');
      const { bytes } = await packRuntimeTarball(root, out);
      expect(bytes).toBeGreaterThan(0);

      const listing = execFileSync('tar', ['-tzf', out], {
        encoding: 'utf8',
        timeout: 30_000,
        killSignal: 'SIGKILL',
      });
      expect(listing).toContain('./package.json');
      expect(listing).toContain('./src/index.ts');
      expect(listing).not.toContain('.git/HEAD');
      expect(listing).not.toContain('node_modules');
      expect(listing).not.toContain('target/bin');
      // security: env files (live secrets + host-specific config) never ship
      expect(listing).not.toContain('.env.local');
      // root backups excluded; nested source backups survives
      expect(listing).not.toContain('./backups/snap.bin');
      expect(listing).toContain('./apps/operator/app/backups/page.tsx');
      // EI-370 regression: neither generated-output tree is packed at all —
      // so a mid-read mutation of a file inside it can never abort the pack.
      expect(listing).not.toContain('operator-vite/dist');
      expect(listing).not.toContain('sidecar/omp');
      rmSync(out, { force: true });
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('EI-370: tolerates a file shrinking mid-read (GNU tar exit 1) instead of throwing', async () => {
    // Reproduces the live failure directly: a file that MUTATES (shrinks)
    // while tar is reading the tree — the class packRuntimeTarball must
    // tolerate per its own doc comment, for any file NOT covered by an
    // exclude (the operator-vite/dist case above is the exclude-it-away
    // fix; this proves the fallback tolerance also holds for a generic
    // live-churning file elsewhere in the tree).
    const root = mkdtempSync(join(tmpdir(), 'pc-pack-shrink-'));
    try {
      writeFileSync(join(root, 'package.json'), '{"name":"x"}');
      mkdirSync(join(root, 'churn'), { recursive: true });
      const churnFile = join(root, 'churn', 'growing.txt');
      // A big enough file that a shrink mid-read is very likely to be
      // observed by tar (small files are read in one syscall and rarely
      // straddle a truncation).
      writeFileSync(churnFile, 'x'.repeat(8 * 1024 * 1024));

      const out = join(root, '..', 'pc-pack-shrink-out.tgz');
      // Truncate the file concurrently with the pack to force GNU tar's
      // "file changed as we read it" exit-1 path.
      const shrinker = (async () => {
        await new Promise((r) => setTimeout(r, 5));
        writeFileSync(churnFile, 'y'.repeat(1024));
      })();
      const packing = packRuntimeTarball(root, out);
      const [{ bytes }] = await Promise.all([packing, shrinker]);
      expect(bytes).toBeGreaterThan(0);
      rmSync(out, { force: true });
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

describe('resolveRuntimeTarball', () => {
  it('reads provider.runtimeTarball and expands ~', () => {
    expect(resolveRuntimeTarball({ target: 'latitude' })).toBeUndefined();
    expect(
      resolveRuntimeTarball({ target: 'latitude', provider: { runtimeTarball: '/x/r.tgz' } }),
    ).toBe('/x/r.tgz');
    expect(
      resolveRuntimeTarball({ target: 'latitude', provider: { runtimeTarball: '~/r.tgz' } }),
    ).toBe(`${process.env.HOME}/r.tgz`);
  });
});
