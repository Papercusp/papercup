/**
 * greenlit-now-stamp.test.ts — the `## Now` banner written when a Blender/Scout
 * draft is greenlit (draft → ready).
 *
 * The property under test is not "a banner appears" but "a reader who trusts the
 * Now block is told the plan is LIVE, nothing the author wrote is lost, and a
 * Now block we did not generate is never touched". All three are asserted
 * through the real parser (`parsePlan`), because the structured `now.state` /
 * `now.next` fields are read at least as often as the prose and are the surface
 * that actually misled agents (see greenlit-now-stamp.ts).
 */

import { describe, expect, it } from 'vitest';
import { parsePlan } from './parser';
import { GREENLIT_NOW_STAMP_MARK, stampGreenlitNowBlock } from './greenlit-now-stamp';
import { buildScoutPlanTemplate } from '../../scout/scout-plan-draft';

const FM = ['---', 'title: T', 'slug: t-2026-08-14', 'status: ready', 'updated: 2026-08-16', '---', ''].join('\n');

function doc(nowBody: string, tail = '\n## Background\n\nBody prose.\n'): string {
  return `${FM}\n# T\n\n## Now\n\n${nowBody}\n${tail}`;
}

/** The real Blender draft Now, verbatim from scout-plan-draft.ts. */
const DRAFT_NOW = [
  '**State:** Draft — autonomously generated by the Blender loop (hive-creative-ideation, D-002/D-010). Awaiting Mug/owner triage; not active until greenlit.',
  '',
  '**Next:** Mug reviews this proposal in the Mug↔Blender feedback loop: it promotes it to greenlight (ready), or `coord:send`s plan-keyed feedback to revise.',
].join('\n');

const AT = new Date('2026-08-16T14:02:49Z');

describe('stampGreenlitNowBlock', () => {
  it('leads BOTH structured fields with the greenlit banner', () => {
    const out = stampGreenlitNowBlock(doc(DRAFT_NOW), 'ready', AT);
    expect(out).not.toBeNull();
    const now = parsePlan(out as string).now;
    expect(now?.state.startsWith(GREENLIT_NOW_STAMP_MARK)).toBe(true);
    expect(now?.state).toContain('APPROVED 2026-08-16');
    // The review-loop instruction must not survive as the parsed `next` — that
    // field is what a resuming agent reads as "the thing to do", and the review
    // is precisely what just finished.
    expect(now?.next.startsWith('Review is COMPLETE')).toBe(true);
    expect(now?.next).not.toMatch(/^Mug reviews/);
  });

  it('destroys nothing — the draft State and Next survive verbatim', () => {
    const out = stampGreenlitNowBlock(doc(DRAFT_NOW), 'ready', AT) as string;
    expect(out).toContain('autonomously generated by the Blender loop');
    expect(out).toContain('not active until greenlit');
    expect(out).toContain('Mug reviews this proposal');
    expect(out).toContain('## Background');
    expect(out).toContain('Body prose.');
  });

  it('is idempotent — re-flipping to ready does not nest a second banner', () => {
    const once = stampGreenlitNowBlock(doc(DRAFT_NOW), 'ready', AT) as string;
    expect(stampGreenlitNowBlock(once, 'ready', AT)).toBeNull();
    expect(once.match(new RegExp(GREENLIT_NOW_STAMP_MARK, 'g'))).toHaveLength(1);
  });

  it('fires ONLY for the ready target', () => {
    for (const status of ['draft', 'shipped', 'superseded', 'active']) {
      expect(stampGreenlitNowBlock(doc(DRAFT_NOW), status, AT)).toBeNull();
    }
  });

  // The safety property, and the NEGATIVE CONTROL for the detector: if this
  // stopped passing, the stamp would be rewriting prose it did not generate.
  it('never touches a Now block we did not generate', () => {
    const handWritten = [
      '**State:** Phase 2 landed; the migration is armed but not applied.',
      '',
      '**Next:** Apply migration 812, then re-run the integration suite.',
    ].join('\n');
    expect(stampGreenlitNowBlock(doc(handWritten), 'ready', AT)).toBeNull();
  });

  it('preserves a hand-written Next even on a draft-marked plan', () => {
    const mixed = [
      '**State:** Draft — autonomously generated by the Blender loop. Awaiting Mug/owner triage; not active until greenlit.',
      '',
      '**Next:** Ship the parser change first — it blocks everything else here.',
    ].join('\n');
    const now = parsePlan(stampGreenlitNowBlock(doc(mixed), 'ready', AT) as string).now;
    expect(now?.state.startsWith(GREENLIT_NOW_STAMP_MARK)).toBe(true);
    // Not the review loop, so it is someone's real plan — keep it exactly.
    expect(now?.next).toBe('Ship the parser change first — it blocks everything else here.');
  });

  it('has no Now block to stamp → null, and never invents one', () => {
    const noNow = `${FM}\n# T\n\n## Background\n\nBody prose.\n`;
    expect(stampGreenlitNowBlock(noNow, 'ready', AT)).toBeNull();
  });

  // RECURRENCE GUARD. The detector keys off one sentence in a template that
  // lives in another package. Pinning it to the real generator means a reworded
  // template FAILS HERE instead of silently disarming the stamp — the class of
  // detector-rot this whole fix exists to prevent.
  it('fires on the REAL Blender draft template (detector pinned to its generator)', () => {
    const realDraft = buildScoutPlanTemplate({
      slug: 'some-proposal-2026-08-14',
      title: 'Some proposal',
      date: '2026-08-14',
    });
    // Sanity: the generator really does emit the marker we key on.
    expect(realDraft).toMatch(/not active until greenlit/i);

    const out = stampGreenlitNowBlock(realDraft, 'ready', AT);
    expect(out).not.toBeNull();
    const now = parsePlan(out as string).now;
    expect(now?.state.startsWith(GREENLIT_NOW_STAMP_MARK)).toBe(true);
    expect(now?.next.startsWith('Review is COMPLETE')).toBe(true);
  });
});
