/**
 * work-items-tools.integration.test.ts — the `work_items:*` TOOL surface
 * end-to-end against real Postgres (BRIEF-test-coverage-fu-workitems-and-crossplan-seam,
 * Part A; unify-work-items-2026-06-04).
 *
 * su-0cbc6's work-items.integration.test.ts drives the work-items.ts ENGINE
 * functions directly. This file drives the 11 `work_items:*` defineTool
 * HANDLERS — the agent-facing surface — so a regression in arg shaping, the
 * `{ ok, … }` JSON envelope, or the error wrapping is caught (the engine test
 * can't see any of that). It walks the lifecycle the old issues-engineer audit
 * flagged, re-pointed at the unified surface:
 *
 *   create (each kind) → get → list → claim → release → set_state (close)
 *     → link (blocks + a non-blocks rel) → tag → subscribe → comment → promote
 *
 * plus the tool-level ERROR envelopes: a feature with no harness, the
 * re-promote guard ("already promoted to <id>"), unknown-harness on promote,
 * an operator-scope item promoted with no harness, and link with no target.
 *
 * NOTE — `work_items:comment` (Threadable, D-003) is now a real verb (added by
 * su-0cbc6 after the parent brief; it was deferred here only because the tool
 * did not exist yet). It dispatches by family: issue-family rides
 * issues-engineer.commentIssue, feature-family threads on the feature ObjectRef.
 * This file covers the TOOL envelope on the issue-family path; the engine-level
 * fan-out is covered in work-items-lifecycle.integration.test.ts.
 *
 * Schema: the column-faithful DDL + migration 142 the engine test uses (no
 * GRANTs / framework roles in the throwaway DB). promote-issue.mintFixFeatureRow
 * + harness-core.resolveProject are mocked (per-harness legacy client / project
 * registry are out of scope for the unified-surface contract).
 */
