/**
 * batch.test.ts — the BULK MUTATION dispatcher `work_items:batch` + the
 * `work_items:claim_next { count }` sweep, end-to-end against real Postgres
 * (work-queue-completeness Phase B, unified-work-item-ledger). Mirrors the fixture
 * wiring of work-items-tools.integration.test.ts.
 *
 *   work_items:batch — each op maps to the existing single-op engine fn; one bad item
 *     never fails the batch; results split ok/failed:
 *       claim · release · set_state · set_priority · tag · subscribe
 *   work_items:claim_next { count } — count>1 returns { claimed: [...] } (oldest-first,
 *     stops when the queue runs dry); omitted/1 keeps the single { workItem } shape.
 */
