describe('work_items:batch (bulk mutations, real PG)', () => {
  it('op:claim claims many items for the caller (and an explicit assignee)', async () => {
    const [a, b] = await seed(['one', 'two']);
    const out = await call(batchTool, {
      op: 'claim',
      harness: 'papercup',
      items: [{ id: a }, { id: b, assignee: 'bee-3' }],
    });
    expect(out.op).toBe('claim');
    expect(out.counts).toEqual({ ok: 2, failed: 0 });
    const results = out.results as { id: string; workItem: { assignee: string } }[];
    expect(results.find((r) => r.id === a)!.workItem.assignee).toBe('su-tester');
    expect(results.find((r) => r.id === b)!.workItem.assignee).toBe('bee-3');
  });

  it('op:set_state moves many items; a missing id is collected, not thrown', async () => {
    const [a, b] = await seed(['x', 'y']);
    const out = await call(batchTool, {
      op: 'set_state',
      harness: 'papercup',
      items: [{ id: a, state: 'in_progress' }, { id: b, state: 'passed' }, { id: 'WI-999', state: 'todo' }],
    });
    expect(out.counts).toEqual({ ok: 2, failed: 1 });
    const results = out.results as { id: string; ok: boolean; error?: string; workItem?: { state: string } }[];
    expect(results.find((r) => r.id === a)!.workItem!.state).toBe('in_progress');
    expect(results.find((r) => r.id === b)!.workItem!.state).toBe('passed');
    const missing = results.find((r) => r.id === 'WI-999')!;
    expect(missing.ok).toBe(false);
    expect(missing.error).toMatch(/not found/);
  });

  it('op:release clears many assignees', async () => {
    const [a, b] = await seed(['r1', 'r2']);
    await call(batchTool, { op: 'claim', harness: 'papercup', items: [{ id: a }, { id: b }] });
    const out = await call(batchTool, { op: 'release', harness: 'papercup', items: [{ id: a }, { id: b }] });
    expect(out.counts).toEqual({ ok: 2, failed: 0 });
    const results = out.results as { workItem: { assignee: string | null } }[];
    expect(results.every((r) => r.workItem.assignee === null)).toBe(true);
  });

  it('op:set_priority sets explicit order and bumps to top', async () => {
    const [a, b] = await seed(['p1', 'p2']);
    const out = await call(batchTool, {
      op: 'set_priority',
      harness: 'papercup',
      items: [{ id: a, priority: 5 }, { id: b, position: 'top' }],
    });
    expect(out.counts).toEqual({ ok: 2, failed: 0 });
    const results = out.results as { id: string; priority: number; applicable: boolean }[];
    expect(results.find((r) => r.id === a)!.priority).toBe(5);
    expect(results.find((r) => r.id === a)!.applicable).toBe(true);
    // bump 'top' lands below the current min (5) → 4
    expect(results.find((r) => r.id === b)!.priority).toBe(4);
  });

  it('op:tag adds + (with remove:true) removes topics', async () => {
    const [a] = await seed(['t1']);
    const added = await call(batchTool, { op: 'tag', harness: 'papercup', items: [{ id: a, topic: 'shop' }] });
    expect(added.counts).toEqual({ ok: 1, failed: 0 });
    expect((added.results as { topic: string }[])[0].topic).toBe('shop');
    const removed = await call(batchTool, { op: 'tag', harness: 'papercup', items: [{ id: a, topic: 'shop', remove: true }] });
    expect(removed.counts).toEqual({ ok: 1, failed: 0 });
  });

  it('op:subscribe follows many items', async () => {
    const [a, b] = await seed(['s1', 's2']);
    const out = await call(batchTool, { op: 'subscribe', harness: 'papercup', items: [{ id: a }, { id: b, mode: 'digest' }] });
    expect(out.counts).toEqual({ ok: 2, failed: 0 });
    expect((out.results as { ok: boolean }[]).every((r) => r.ok)).toBe(true);
  });

  it('a per-item validation gap (set_state without state) is collected, not thrown', async () => {
    const [a] = await seed(['v1']);
    const out = await call(batchTool, { op: 'set_state', harness: 'papercup', items: [{ id: a }] });
    expect(out.counts).toEqual({ ok: 0, failed: 1 });
    expect((out.results as { error: string }[])[0].error).toMatch(/requires `state`/);
  });
});

describe('work_items:claim_next { count } (real PG)', () => {
  it('count omitted → backward-compatible single { workItem } shape', async () => {
    await seed(['only']);
    const out = await call(claimNextTool, { harness: 'papercup' });
    expect(out.ok).toBe(true);
    expect((out.workItem as { id: string }).id).toMatch(/^WI-\d+$/);
    expect(out.claimed).toBeUndefined();
  });

  it('count>1 claims up to N oldest items and returns { claimed: [...] }', async () => {
    const ids = await seed(['c1', 'c2', 'c3']); // oldest-first
    const out = await call(claimNextTool, { harness: 'papercup', count: 2 });
    expect(out.ok).toBe(true);
    const claimed = out.claimed as { id: string; assignee: string }[];
    expect(claimed).toHaveLength(2);
    // oldest-first (created_ts ASC) → the first two seeded ids, claimed by the caller
    expect(claimed.map((c) => c.id)).toEqual([ids[0], ids[1]]);
    expect(claimed.every((c) => c.assignee === 'su-tester')).toBe(true);
    // the third remains claimable — work_items:get returns the house bulk envelope
    // ({ results:[{ workItem }] }, D-001), so unwrap the single result by id.
    const third = await call(getTool, { id: ids[2] });
    const thirdItem = (third.results as { workItem: { assignee: string | null } }[])[0]!.workItem;
    expect(thirdItem.assignee).toBeNull();
  });

  it('count>1 STOPS at the first miss — returns fewer than count when the queue runs dry', async () => {
    await seed(['lonely']); // only one claimable
    const out = await call(claimNextTool, { harness: 'papercup', count: 5 });
    expect(out.ok).toBe(true);
    expect((out.claimed as unknown[]).length).toBe(1);
  });

  it('count>1 over an empty queue → { ok:false, claimed: [] }', async () => {
    const out = await call(claimNextTool, { harness: 'papercup', count: 3 });
    expect(out.ok).toBe(false);
    expect(out.claimed).toEqual([]);
  });
});
