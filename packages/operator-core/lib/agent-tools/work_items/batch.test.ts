const CTX = { isSuperuser: true, uiClientId: 'su-tester', workspaceId: 'default' } as never;

async function call(tool: { handler: (a: never, c: never) => Promise<unknown> }, args: Record<string, unknown>) {
  const res = (await tool.handler(args as never, CTX)) as { content: { text: string }[] };
  return JSON.parse(res.content[0]!.text) as Record<string, unknown>;
}

/** Create N feature work-items on `harness` and return their ids (oldest-first). */
async function seed(titles: string[], harness = 'papercup'): Promise<string[]> {
  const out = await call(createBatchTool, { harness, items: titles.map((t) => ({ kind: 'feature', title: t })) });
  return (out.created as { id: string }[]).map((c) => c.id);
}

