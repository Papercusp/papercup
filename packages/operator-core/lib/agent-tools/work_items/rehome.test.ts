import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { REHOME_DEPENDENT_TABLES } from './rehome';

/**
 * workspace-work-scope-policy-2026-09-04 P-009 — recurrence guard.
 *
 * `rehomeWorkItem` moves a work-item's dependent rows with one `UPDATE
 * harness_shared.<table>` per entry of REHOME_DEPENDENT_TABLES, inside ONE
 * transaction. An entry that names a VIEW aborts the whole move with
 * `cannot update view "<name>"` — measured live on 2026-09-05 when
 * `triage_routed_items` (a view over work_items, 894-triage-corpus-views.sql) sat in
 * the list: all five P-009 backfill moves rolled back.
 *
 * The schema mirror (`libs/db/src/schema/generated.ts`, regenerated by
 * pull-schema.mjs) declares every relation as `harnessShared.table(...)` or
 * `harnessShared.view(...)`, so the base-table-ness of each entry is pinned here
 * instead of being rediscovered at the next live move.
 */
const GENERATED_SCHEMA = fileURLToPath(
  new URL('../../../../../libs/papercusp/libs/db/src/schema/generated.ts', import.meta.url),
);

function relationKind(schemaSource: string, name: string): 'table' | 'view' | 'absent' {
  if (schemaSource.includes(`harnessShared.table("${name}"`)) return 'table';
  if (schemaSource.includes(`harnessShared.view("${name}"`)) return 'view';
  return 'absent';
}

describe('REHOME_DEPENDENT_TABLES', () => {
  const schema = readFileSync(GENERATED_SCHEMA, 'utf8');

  it('names only base TABLES in harness_shared (a view aborts the whole re-home transaction)', () => {
    const kinds = Object.fromEntries(REHOME_DEPENDENT_TABLES.map((t) => [t, relationKind(schema, t)]));
    expect(kinds).toEqual(Object.fromEntries(REHOME_DEPENDENT_TABLES.map((t) => [t, 'table'])));
  });

  it('calibration: the instrument tells a view from a table (triage_routed_items IS a view)', () => {
    // If this control ever fails, `relationKind` has gone blind and the guard above
    // would pass vacuously — fix the instrument, not the list.
    expect(relationKind(schema, 'triage_routed_items')).toBe('view');
    expect(relationKind(schema, 'work_items')).toBe('table');
    expect(relationKind(schema, 'no-such-relation-zzz')).toBe('absent');
  });

  it('every dependent table carries the (workspace_id, harness_slug, feature_id) key the UPDATE filters on', () => {
    for (const t of REHOME_DEPENDENT_TABLES) {
      const start = schema.indexOf(`harnessShared.table("${t}"`);
      expect(start, `${t} declared`).toBeGreaterThanOrEqual(0);
      // The drizzle table literal runs from the opening `{` to the matching `})` that
      // closes the column map; a bounded window is enough to see the key columns.
      const body = schema.slice(start, schema.indexOf('\n}', start) + 2);
      for (const col of ['"workspace_id"', '"harness_slug"', '"feature_id"']) {
        expect(body, `${t} has column ${col}`).toContain(col);
      }
    }
  });
});
