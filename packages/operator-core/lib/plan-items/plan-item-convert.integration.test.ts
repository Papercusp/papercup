/**
 * plan-item-convert.integration.test.ts — convert-at-pickup end-to-end against
 * real Postgres (project-centric-harness-rethink D-015 / unify-work-items /
 * plan-item-assignment-claim-liveness).
 *
 * Drives convertPlanItem over the REAL stores: migrations 140/141 (assignment +
 * leased claims), 131/142/152 (engineer_issues + WI ids + task kind), the coord
 * capability tables (links), and a column-faithful hfc — with getOrgPg pointed
 * at a throwaway DB and the plan source mocked (the same seams the sibling
 * plan-items + work-items integration tests use).
 *
 * Proves the D-015 contract:
 *  • pickup = ONE call: policy-checked lease + work_item mint + claim + back-link.
 *  • idempotent: re-pickup RESUMES the same work_item (no duplicate).
 *  • refused/conflicted pickups create NOTHING.
 *  • the back-link is both the `implements` edge AND the payload stamp.
 *  • a lapsed peer's execution record is taken over by the new lease holder.
 */
