// C2 [P2] — invalid-state rejection is ASYMMETRIC across the families (work-items.ts:679 →
// normalizeWorkItemState). The issue family has a 3-state CHECK (engineer_issues), so an
// unmappable state is a TYPED engine-level refusal that LISTS the valid issue set. The feature
// family's hfc.status carries NO CHECK (the pipeline owns that vocabulary), so an arbitrary state
// passes THROUGH un-rejected — there is no feature "valid set" to list. (The brief's premise that
// a feature also throws is incorrect for this engine; the test asserts the ACTUAL asymmetry, which
// is the more important contract: the two families behave differently, and the issue error names
// the issue states.)
describe('C2 — setWorkItemState invalid-state rejection (per-family asymmetry)', () => {
  it('issue-family rejects an unmappable state with a TYPED error LISTING the issue valid-set', async () => {
    const bug = await wi.createWorkItem({ kind: 'bug', title: 'b', harness: 'papercup', createdBy: 'agA' });
    let caught: Error | null = null;
    try {
      await wi.setWorkItemState(bug.id, 'validating'); // a feature-only state — invalid for an issue
    } catch (e) {
      caught = e as Error;
    }
    expect(caught).not.toBeNull();
    // The message names the issue family's native + accepted-alias set (not a raw PG CHECK error).
    expect(caught!.message).toMatch(/cannot take state 'validating'/);
    expect(caught!.message).toMatch(/valid: open, wip, blocked, needs-human, done, dropped, resolved, closed/);
    expect(caught!.message).not.toMatch(/engineer_issues_state_check/); // never leaks the PG constraint
  });

  // P-011 / D-010 (GAP 5): the feature family now VALIDATES agent-set states against the
  // canonical set — a truly-unknown status is rejected (was silently accepted, dropping the
  // item out of dispatch). The pipeline's raw-SQL phase writes still bypass this path.
  it('feature-family REJECTS a truly-unknown agent-set state with the valid set (GAP 5 typo guard)', async () => {
    const feat = await wi.createWorkItem({ kind: 'feature', title: 'f', harness: 'papercup', createdBy: 'agA' });
    await expect(wi.setWorkItemState(feat.id, 'some-novel-pipeline-phase', { harness: 'papercup' }))
      .rejects.toThrow(/cannot take state 'some-novel-pipeline-phase' — valid: .*in_progress/);
    // unchanged in the DB (still open — the unified claimable entry state) — not dropped into a non-dispatchable limbo.
    expect((await db.sql`SELECT status FROM harness_shared.harness_features_consolidated WHERE feature_id=${feat.id}`)[0].status)
      .toBe('open');
  });

  it('feature-family NORMALIZES a separator/case drift typo to the unified token (In-Progress → wip)', async () => {
    const feat = await wi.createWorkItem({ kind: 'feature', title: 'f', harness: 'papercup', createdBy: 'agA' });
    const after = await wi.setWorkItemState(feat.id, 'In-Progress', { harness: 'papercup' });
    expect(after?.state).toBe('wip');
  });

  it('a trusted restore (allowNonCanonical) bypasses the guard — feature only', async () => {
    const feat = await wi.createWorkItem({ kind: 'feature', title: 'f', harness: 'papercup', createdBy: 'agA' });
    const after = await wi.setWorkItemState(feat.id, 'some-raw-pipeline-phase', { harness: 'papercup', allowNonCanonical: true });
    expect(after?.state).toBe('some-raw-pipeline-phase');
  });

  it('both families now reject gibberish (issue via its CHECK dialect, feature via the canonical set)', async () => {
    const bug = await wi.createWorkItem({ kind: 'bug', title: 'b', harness: 'papercup', createdBy: 'agA' });
    const feat = await wi.createWorkItem({ kind: 'feature', title: 'f', harness: 'papercup', createdBy: 'agA' });
    await expect(wi.setWorkItemState(bug.id, 'gibberish')).rejects.toThrow(/cannot take state 'gibberish'/);
    await expect(wi.setWorkItemState(feat.id, 'gibberish', { harness: 'papercup' })).rejects.toThrow(/cannot take state 'gibberish'/);
  });
});

// WI-1403 — completion-integrity gate (work-item-completion-integrity-2026-07-01,
// contract C-1): a work_item may reach a TERMINAL state (feature: passed|deprecated;
// issue: resolved|closed) ONLY via a transition carrying BOTH an owner (`by`) and a
// `completionRef`. This is the recurrence guard the Queen brief requires — it fails
// if a terminal transition ever slips through without both, or if a
// `skipCompletionGate` flip (the watchdog/system-sweep bypass, WI-1404) ever writes a
