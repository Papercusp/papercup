/** The fan-out events captured by the spy: [ObjectRef, InjectEvent, opts]. */
interface FanoutCall {
  ref: { kind: string; ref: string };
  ev: { notify_kind: string; isResolution?: boolean; summary: string };
  opts: { excludeId?: string };
}
function fanoutCalls(): FanoutCall[] {
  return fh.spy.mock.calls.map((c) => ({ ref: c[0], ev: c[1], opts: c[2] } as FanoutCall));
}

