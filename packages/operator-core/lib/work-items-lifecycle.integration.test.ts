/**
 * work-items-lifecycle.integration.test.ts — engine-level lifecycle EDGES the
 * happy-path work-items.integration.test.ts (su-0cbc6) doesn't cover
 * (BRIEF-test-coverage-fu-workitems-and-crossplan-seam, Part A).
 *
 * Covers the behaviours the unified surface inherits from the issue-family
 * substrate, which are invisible in the tool envelopes:
 *
 *   • the change FAN-OUT mapping — every work-item mutation calls deliver() →
 *     fanoutForObject with the right notify_kind (issue_created / issue_updated /
 *     issue_commented / issue_resolved) and the ACTOR EXCLUDED (an agent is never
 *     notified of its own action). Asserted via a fanoutForObject spy.
 *   • the comment (Threadable) path — commentIssue creates a thread post + a
 *     'issue_commented' fan-out. (There is no work_items:comment tool yet; the
 *     issue-family commentIssue is the work_item[kind=bug|change] comment path.)
 *   • the link projection for NON-`blocks` rels (relates / duplicates / fixes).
 *   • promote SIDE-EFFECTS: a successful promote sets linkedFeatureId + auto-adds
 *     a "Promoted to <F-FIX>" comment; the re-promote guard then reads that.
 *
 * Drives the work-items.ts engine + issues-engineer.commentIssue against real PG
 * (migration 142 + 131). fanoutForObject is replaced by a spy so the deliver()
 * MAPPING is asserted deterministically without coupling to the full
 * subscribe→inject substrate (covered separately by the coordination fan-out
 * tests). mintFixFeatureRow / resolveProject are mocked (per-harness legacy
 * client out of scope).
 */
