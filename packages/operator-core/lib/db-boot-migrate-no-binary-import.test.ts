import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * WI-7540 recurrence guard.
 *
 * `db-boot-migrate.ts` runs SQL migrations. It needs `applyPendingMigrations` +
 * `defaultSkipFile`, both of which are DEFINED in
 * `@papercusp/embedded-postgres-server/src/migration-runner.js`.
 *
 * The package BARREL (`src/index.js`) re-exports those two symbols, but it also
 * carries a top-level `import EmbeddedPostgres from 'embedded-postgres'`, which
 * resolves the platform binary package `@embedded-postgres/<platform>` at
 * module-load time. Importing the barrel therefore makes a pure-migration code
 * path depend on a POSTGRES BINARY.
 *
 * That is not a theoretical smell. Measured on the packaged mac dogfood bundle
 * (WI-3307, 2026-08-03): the `dev` env operator bound :3270 and then died with
 *
 *   ERR_MODULE_NOT_FOUND: Cannot find package '@embedded-postgres/darwin-x64'
 *     imported from <tree>/node_modules/embedded-postgres/dist/binary.js
 *
 * because `source.tar.zst` ships no `@embedded-postgres/*` platform package at
 * all. The chain was entirely STATIC —
 *
 *   agent-tools registry -> agent-tools/release/checkpoint-run.ts
 *     -> db-boot-migrate.ts -> embedded-postgres-server/src/index.js
 *       -> embedded-postgres/dist/binary.js -> @embedded-postgres/<platform>
 *
 * — which is why no env knob could gate it: re-running with
 * PAPERCUSP_USE_EMBEDDED_PG=0 plus external HARNESS_*_DATABASE_URL reproduced
 * the identical crash. The dev button was simply dead in the shipped bundle.
 *
 * This is asserted at the SOURCE level on purpose. A load-time assertion would
 * pass on any machine that happens to have the platform binary installed (every
 * Linux dev box does), i.e. it would be green exactly where the bug is invisible
 * and silent exactly where it bites. Reading the import specifier is
 * platform-independent.
 */
describe('db-boot-migrate does not drag a Postgres binary into the migration path', () => {
  const source = readFileSync(join(__dirname, 'db-boot-migrate.ts'), 'utf8');

  /**
   * Collect the specifier of every real `import ... from '<spec>'` STATEMENT.
   *
   * Deliberately NOT done by stripping comments first. The explanatory prose in
   * db-boot-migrate.ts necessarily names the barrel and the binary packages, and
   * a naive comment-stripper is worse than useless here: an earlier draft of this
   * test stripped block comments before line comments, so the `/*` inside a
   * `// @embedded-postgres/...` line opened a PHANTOM block comment that swallowed
   * the entire import section — and the test then failed while the source was
   * perfectly correct.
   *
   * Anchoring on `^import` is both simpler and stronger: a comment line begins
   * with `//` or `*`, never with `import`, so prose can never be mistaken for an
   * import, and an import can never be hidden by prose.
   */
  const importedSpecifiers = [...source.matchAll(/^import\s[\s\S]*?from\s*['"]([^'"]+)['"]/gm)].map(
    (m) => m[1],
  );

  it('imports the migration runner module, not the package barrel', () => {
    expect(
      importedSpecifiers.includes('@papercusp/embedded-postgres-server'),
      "db-boot-migrate.ts must not import the '@papercusp/embedded-postgres-server' " +
        'BARREL: src/index.js statically imports `embedded-postgres`, which resolves ' +
        'the @embedded-postgres/<platform> BINARY package at module-load time and ' +
        'crashes any environment that lacks it (WI-7540 — this killed the packaged ' +
        "`dev` env operator on mac). Import the symbols you need from " +
        "'@papercusp/embedded-postgres-server/src/migration-runner.js' instead; both " +
        'applyPendingMigrations and defaultSkipFile are defined there, and ' +
        'src/migration-runner.d.ts is generated by the same gen:types script, so types ' +
        'are unaffected.',
    ).toBe(false);
  });

  it('never imports the embedded-postgres package (or its platform binary) directly', () => {
    const direct = importedSpecifiers.filter(
      (s) => s === 'embedded-postgres' || s.startsWith('@embedded-postgres/'),
    );

    expect(
      direct,
      'db-boot-migrate.ts must not import `embedded-postgres` or an ' +
        '`@embedded-postgres/<platform>` package. Running migrations needs a Postgres ' +
        'CLIENT, never a Postgres BINARY (WI-7540).',
    ).toEqual([]);
  });

  it('still imports the two symbols it actually needs', () => {
    // Guards against "satisfying" the rule by deleting the import outright.
    expect(importedSpecifiers).toContain(
      '@papercusp/embedded-postgres-server/src/migration-runner.js',
    );
    expect(source).toMatch(/applyPendingMigrations/);
    expect(source).toMatch(/defaultSkipFile/);
  });
});
