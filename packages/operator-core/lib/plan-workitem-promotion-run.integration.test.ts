/**
 * plan-workitem-promotion-run.integration.test.ts — the DB-level proof of the
 * promotion RUNNER (unified-work-item-ledger-2026-06-21 P-006) against real Postgres.
 *
 * The pure core (computePromotions) is unit-tested in plan-workitem-promotion.test.ts;
 * this drives `promotePlanItems` over the REAL stores (createWorkItem → the work_items
 * base, linkWorkItem → coord_links, listConvertedPlanItemRefs → the implements edge),
 * with getOrgPg pointed at a throwaway DB, the plan source mocked, and the
 * papercusp-plan-workitem-promotion flag forced ON — the same seams the sibling
 * plan-items/work-items integration tests use.
 *
 * Proves the P-006 contract:
 *  • starting a plan with N open items mints N PLACEABLE (unclaimed) feature work-items,
 *    each tied to the plan via source_plan_slug + an `implements` edge;
 *  • re-running is IDEMPOTENT — no duplicate rows, promoted=0 the second time;
 *  • a plan with only done/dropped items promotes NOTHING;
 *  • newly-opened items promote incrementally without re-minting the existing ones.
 */
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import type postgres from 'postgres';
import { createFreshPgDb, type FreshPgDb } from '../test/_pg-helpers';
import { HARNESS_FEATURES_CONSOLIDATED_DDL, USER_TRUST_LIST_DDL } from '../test/_work-items-schema';
import { ensureCoordCapabilityTables } from '@papercusp/coordination/capabilities';

const COORD_EVENT_LOG_DDL = `
  CREATE TABLE IF NOT EXISTS harness_shared.coord_event_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id text NOT NULL DEFAULT 'default',
    surface text NOT NULL, writer_key text, msg_id text NOT NULL,
    body jsonb NOT NULL, ts timestamptz NOT NULL DEFAULT now())`;

const h = vi.hoisted(() => ({
  sql: undefined as unknown as postgres.Sql,
  plans: new Map<string, { items: { id: string; status: string; text?: string }[]; title?: string }>(),
  flagOn: true,
}));

vi.mock('@papercusp/db-org', async () => {
  const actual = await vi.importActual<typeof import('@papercusp/db-org')>('@papercusp/db-org');
  return { ...actual, getOrgPg: () => ({ sql: h.sql }) };
});
vi.mock('./workspace-registry', async () => {
  const actual = await vi.importActual<typeof import('./workspace-registry')>('./workspace-registry');
  return { ...actual, activeWorkspaceId: () => 'default' };
});
vi.mock('./harness-core', async () => {
  const actual = await vi.importActual<typeof import('./harness-core')>('./harness-core');
  return { ...actual, resolveProject: async (slug: string) => ({ slug, path: `/tmp/${slug}` }) };
});
// Force the promotion flag ON — promotePlanItems early-returns flagOff when getFlag is false.
vi.mock('@papercusp/flags/server', async () => {
  const actual = await vi.importActual<typeof import('@papercusp/flags/server')>('@papercusp/flags/server');
  return { ...actual, getFlag: async () => h.flagOn };
});
vi.mock('./agent-tools/plans/source', () => ({
  readPlanBySlug: async (slug: string) => {
    const p = h.plans.get(slug);
    if (!p) return null;
    return {
      archived: false,
      parsed: {
        frontmatter: p.title ? { title: p.title } : {},
        now: null,
        decisions: [],
        items: p.items.map((i) => ({ id: i.id, storedStatus: i.status, text: i.text ?? '', decisionRefs: [] })),
      },
      row: { items: p.items.map((i) => ({ id: i.id, status: i.status, text: i.text ?? '' })) },
    };
  },
}));

const run = await import('./plan-workitem-promotion-run');
const convert = await import('./plan-items/convert');
const { planItemRef } = await import('./issue-blocks-merge');

let db: FreshPgDb;

const WS = 'default';
const HARNESS = 'papercup';
const PLAN = 'demo-promote-plan';

beforeAll(async () => {
  db = await createFreshPgDb('plan-workitem-promotion-run');
  h.sql = db.sql;
  await ensureCoordCapabilityTables(db.sql);
  await db.sql.unsafe(COORD_EVENT_LOG_DDL);
  await db.sql.unsafe(HARNESS_FEATURES_CONSOLIDATED_DDL);
  await db.sql.unsafe(USER_TRUST_LIST_DDL);
  await db.sql.unsafe(`
    ALTER TABLE harness_shared.work_items
      ADD COLUMN IF NOT EXISTS assignee_rank integer, ADD COLUMN IF NOT EXISTS rank_writer text,
      ADD COLUMN IF NOT EXISTS rank_updated_at timestamptz;
    CREATE TABLE IF NOT EXISTS harness_shared.contributors (
      workspace_id text NOT NULL, harness_slug text NOT NULL,
      github_user_id bigint NOT NULL, github_username text NOT NULL DEFAULT '');
  `).simple();
}, 90_000);

afterAll(async () => {
  await db.cleanup();
});

beforeEach(async () => {
  await db.sql`TRUNCATE harness_shared.work_items, harness_shared.coord_links, harness_shared.coord_event_log, harness_shared.contributors RESTART IDENTITY`;
  await db.sql`ALTER SEQUENCE harness_shared.work_item_seq RESTART WITH 1`;
  h.flagOn = true;
  h.plans.clear();
});

const features = () =>
  db.sql<{ feature_id: string; title: string; source_plan_slug: string | null; taken_by: string | null }[]>`
    SELECT feature_id, title, source_plan_slug, taken_by
      FROM harness_shared.harness_features_consolidated
     WHERE item_kind = 'feature' ORDER BY feature_id`;

const base = { workspaceId: WS, harnessSlug: HARNESS, planSlug: PLAN, createdBy: 'su-test' };

describe('promotePlanItems (P-006): plan → placeable work-items, against real PG', () => {
  it('mints one PLACEABLE feature work-item per OPEN item, tied to the plan; done/dropped are skipped', async () => {
    h.plans.set(PLAN, {
      items: [
        { id: 'P-001', status: 'todo', text: 'Build the frontier gate' },
        { id: 'P-002', status: 'wip', text: 'Wire the runner' },
        { id: 'P-003', status: 'done', text: 'Already shipped' },
        { id: 'P-004', status: 'dropped', text: 'Abandoned' },
      ],
    });
    const res = await run.promotePlanItems(base);
    expect(res.promoted).toBe(2); // only the two open items (todo + wip)
    expect(res.flagOff).toBeUndefined();

    const rows = await features();
    expect(rows.map((r) => r.title)).toEqual(['Build the frontier gate', 'Wire the runner']);
    // Tied to the plan via the first-class column…
    expect(rows.every((r) => r.source_plan_slug === PLAN)).toBe(true);
    // …and PLACEABLE: unclaimed (no owner) — the Queen places them.
    expect(rows.every((r) => r.taken_by === null || r.taken_by === '')).toBe(true);

    // Each carries an implements edge back to its plan-item (the idempotency truth).
    const refs = await convert.listConvertedPlanItemRefs();
    expect(refs.has(planItemRef(PLAN, 'P-001'))).toBe(true);
    expect(refs.has(planItemRef(PLAN, 'P-002'))).toBe(true);
    expect(refs.has(planItemRef(PLAN, 'P-003'))).toBe(false);
  });

  it('is IDEMPOTENT — re-running mints no duplicates (promoted=0, same rows)', async () => {
    h.plans.set(PLAN, {
      items: [
        { id: 'P-001', status: 'todo', text: 'Item one' },
        { id: 'P-002', status: 'todo', text: 'Item two' },
      ],
    });
    const first = await run.promotePlanItems(base);
    expect(first.promoted).toBe(2);
    const idsAfterFirst = (await features()).map((r) => r.feature_id);

    const again = await run.promotePlanItems(base);
    expect(again.promoted).toBe(0);
    expect(again.skipped).toBe(2);
    const idsAfterSecond = (await features()).map((r) => r.feature_id);
    expect(idsAfterSecond).toEqual(idsAfterFirst); // no new rows
  });

  it('a plan with ONLY done/dropped items promotes NOTHING', async () => {
    h.plans.set(PLAN, {
      items: [
        { id: 'P-001', status: 'done', text: 'Done' },
        { id: 'P-002', status: 'dropped', text: 'Dropped' },
      ],
    });
    const res = await run.promotePlanItems(base);
    expect(res.promoted).toBe(0);
    expect(await features()).toHaveLength(0);
  });

  it('promotes incrementally — a newly-opened item is minted without re-minting the existing ones', async () => {
    h.plans.set(PLAN, { items: [{ id: 'P-001', status: 'todo', text: 'First' }] });
    expect((await run.promotePlanItems(base)).promoted).toBe(1);

    // A second item is added open later; re-running promotes only the new one.
    h.plans.set(PLAN, {
      items: [
        { id: 'P-001', status: 'wip', text: 'First' },
        { id: 'P-002', status: 'todo', text: 'Second' },
      ],
    });
    const res = await run.promotePlanItems(base);
    expect(res.promoted).toBe(1);
    expect((await features()).map((r) => r.title).sort()).toEqual(['First', 'Second']);
  });

  it('is a NO-OP when the flag is OFF (flagOff:true, nothing minted)', async () => {
    h.flagOn = false;
    h.plans.set(PLAN, { items: [{ id: 'P-001', status: 'todo', text: 'Should not mint' }] });
    const res = await run.promotePlanItems(base);
    expect(res).toMatchObject({ promoted: 0, flagOff: true });
    expect(await features()).toHaveLength(0);
  });

  it('an unknown plan promotes nothing (no throw)', async () => {
    const res = await run.promotePlanItems({ ...base, planSlug: 'no-such-plan' });
    expect(res.promoted).toBe(0);
  });
});
