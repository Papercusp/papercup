/**
 * plan-workitem-promotion-run.integration.test.ts — the DB-level proof of the
 * promotion RUNNER (unified-work-item-ledger-2026-06-21 P-006) against real Postgres.
 *
 * The pure core (computePromotions) is unit-tested in plan-workitem-promotion.test.ts;
 * this drives `promotePlanItems` over the REAL stores (createWorkItem → the work_items
 * base, linkWorkItem → coord_links, listConvertedPlanItemRefs → the implements edge),
 * with getOrgPg pointed at a throwaway DB, the plan source mocked, and the
 * papercusp-plan-workitem-promotion flag forced ON — the same seams the sibling
 * plan-items/work-items integration tests use.
 *
 * Proves the P-006 contract:
 *  • starting a plan with N open items mints N PLACEABLE (unclaimed) feature work-items,
 *    each tied to the plan via source_plan_slug + an `implements` edge;
 *  • re-running is IDEMPOTENT — no duplicate rows, promoted=0 the second time;
 *  • a plan with only done/dropped items promotes NOTHING;
 *  • newly-opened items promote incrementally without re-minting the existing ones.
 */
