const BOOT_MIGRATE_IDENTITY: AgentIdentity = {
  ownerId: 'boot-migrate',
  ownerLabel: 'boot-migrate',
  source: 'static-client',
  workspaceId: null,
  userId: null,
};

let _ran = false;

// EI-19320461261471579: ride out a transaction-CONTENTION failure instead of
// leaving the migration pending. This path is not only operator boot — the
// green-checkpoint gate calls it as its migration PREFLIGHT, and a preflight
// that leaves a migration pending aborts the whole run as INCONCLUSIVE
// (`green: null`, reason 'migrations-pending'), holding main for the entire
// fleet. Observed live twice in 11 minutes on 2026-08-02 (05:50Z, 06:01Z):
// migration 721 alters harness_shared.work_items, whose two dependent views
// make an `ALTER TABLE …; CREATE OR REPLACE VIEW …` a guaranteed lock-order
// inversion against ordinary fleet readers.
//
// The budget is deliberately MUCH tighter than db:migrate's (2s→30s over 5
// attempts): that tool is an agent waiting on one deliberate apply, whereas
// this runs on the operator's boot path, where a 30s stall delays the dev-api
// the whole fleet shares. A deadlock does not need a long wait — Postgres has
// ALREADY broken the cycle by killing one side, so the retry is about letting
// the surviving transaction commit, not about waiting out a long-lived holder.
// ~1.2s worst case, then fall through to the existing leave-it-pending path.
const CONTENTION_RETRY_MAX_ATTEMPTS = 3;
const CONTENTION_RETRY_BASE_DELAY_MS = 400;
const CONTENTION_RETRY_MAX_DELAY_MS = 2000;

/** Exponential backoff for contention retry attempt N (1-based): 400ms, 800ms,
 *  capped at 2s. Pure — unit tested. */
export function contentionRetryBackoffMs(attempt: number): number {
  return Math.min(CONTENTION_RETRY_BASE_DELAY_MS * 2 ** (attempt - 1), CONTENTION_RETRY_MAX_DELAY_MS);
}

const sleep = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms));

// EI-19403856469813053: a CROSS-BOOT cooldown for a migration file that keeps
// failing. The original symptom this closes: migration 727 (an ALTER on
// harness_shared.work_items — a table with dependent VIEWS, per the
// engineer_issues/harness_features_consolidated pattern) sat pending and
// FAILING (a NOT NULL abort) for ~30 minutes on 2026-08-03. Every single
// operator boot AND every green-checkpoint gate preflight during that window
// (this function is that preflight — see checkpoint-run.ts / green-checkpoint.ts)
// called applyPendingMigrationsNow() fresh, which re-attempted the SAME known-
// broken ALTER — taking a real ACCESS EXCLUSIVE lock on work_items each time,
// before failing and rolling back. Under fleet load (frequent operator boots +
// frequent gate re-fires), that repeats every few minutes for as long as the
// migration stays broken, each time stalling every reader of work_items (and
// its dependent views) for up to their own lock_timeout.
//
// This does NOT change retry-until-fixed semantics — a broken migration still
// gets retried once the cooldown elapses, and a human/agent fixing the file
// still gets it applied promptly (cooldown, not a permanent skip). It only
// stops the SAME known-broken file from re-taking a full-strength lock on
// literally every boot within a short window. Deliberately file-based (not a
// DB table): this path runs BEFORE we know the schema is even healthy, so it
// must not depend on schema state of its own to bootstrap, and a shared file
// under ~/.papercusp naturally scopes the cooldown to "this box", matching
// where the amplification (many agents booting on the SAME shared PG) occurs.
// Best-effort throughout: a read/write failure here must never affect whether
// migrations actually apply — this is a rate-limiting optimization, not a
// correctness mechanism (the schema_migrations ledger stays the sole source of
// truth for what's applied).
export const MIGRATION_FAILURE_COOLDOWN_MS = 5 * 60 * 1000; // 5 minutes

/** Resolve the cooldown duration. Overridable (PAPERCUSP_MIGRATION_COOLDOWN_MS)
 *  purely for test isolation (a real cooldown run would otherwise take 5 real
 *  minutes to observe expiry) — not intended as an operational tuning knob. */
export function resolveMigrationFailureCooldownMs(env: NodeJS.ProcessEnv = process.env): number {
  const raw = env.PAPERCUSP_MIGRATION_COOLDOWN_MS;
  const parsed = raw ? Number(raw) : NaN;
  return Number.isFinite(parsed) && parsed >= 0 ? parsed : MIGRATION_FAILURE_COOLDOWN_MS;
}

interface MigrationCooldownEntry {
  lastFailedAt: number;
  error: string;
  attempts: number;
}
type MigrationCooldownState = Record<string, MigrationCooldownEntry>;

/** Resolve the cooldown state file path. Overridable (PAPERCUSP_MIGRATION_COOLDOWN_FILE)
 *  for test isolation — mirrors the PAPERCUSP_PG_DATA_DIR override convention already
 *  used by @papercusp/embedded-postgres-server for the same reason. */
export function resolveMigrationCooldownFilePath(env: NodeJS.ProcessEnv = process.env): string {
  return env.PAPERCUSP_MIGRATION_COOLDOWN_FILE || join(homedir(), '.papercusp', 'migration-failure-cooldown.json');
}

async function readMigrationCooldownState(path: string): Promise<MigrationCooldownState> {
  try {
    const parsed: unknown = JSON.parse(await readFile(path, 'utf8'));
    return parsed && typeof parsed === 'object' ? (parsed as MigrationCooldownState) : {};
  } catch {
    return {}; // missing file / corrupt JSON — treat as "nothing cooling down"
  }
}

async function writeMigrationCooldownState(path: string, state: MigrationCooldownState): Promise<void> {
  try {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, JSON.stringify(state), 'utf8');
  } catch {
    /* best-effort — see module-level rationale above */
  }
}

export interface BootMigrateResult {
  applied: number;
  failed: { file: string; error: string }[];
}

/** Apply pending sql/*.sql on operator boot (native box). Idempotent per
 *  process (the schema_migrations tracker also makes a re-run a no-op).
 *  Never throws — a failure leaves migrations pending, it never wedges boot. */
export async function applyPendingMigrationsAtBoot(): Promise<BootMigrateResult | null> {
  if (_ran) return null;
  _ran = true;
  return applyPendingMigrationsNow();
}

/**
 * EI-13992: the UNGUARDED core of {@link applyPendingMigrationsAtBoot} — no
 * `_ran` singleton, safe to call from any per-invocation caller (not just
 * once-per-process boot). Extracted so the green-checkpoint gate can apply
 * pending migrations to the live dev PG as a PREFLIGHT, independent of
 * operator boot: the self-sustaining deadlock this closes is "gate red →
 * main frozen → db-boot-migrate (boot-only) never re-fires → dev PG stays
 * behind → tests asserting new columns fail → gate stays red". A gate run
 * happens on its own schedule regardless of whether main is frozen, so
 * applying migrations HERE — every run, not just at boot — means the dev PG
 * can never drift far enough behind to red-pin the gate on missing-column
 * failures again. Same idempotent runner (the schema_migrations tracker
 * makes a re-run with nothing pending a fast no-op); never throws. */
export async function applyPendingMigrationsNow(): Promise<BootMigrateResult | null> {
  const sqlDir = resolveSqlDir();
  if (!sqlDir) {
    // EI-18737837917400418: this used to be a console.warn — easy to miss on a
    // packaged/headless boot where nobody is watching the console, and the
    // silence let the EI-13992 safety net stay dark for a real deploy for days.
    // Log LOUD, with exactly what was tried, so a misconfigured
    // PAPERCUSP_PG_SQL_DIR (or a genuinely missing sql dir) is diagnosable from
    // the boot log alone instead of requiring a live repro.
    console.error(
      `[boot-migrate] sql dir not found — skipping boot apply. Candidates tried: ${sqlDirCandidates().join(', ')}`,
    );
    return null;
  }

  // A parked code/data migration remains recognizable after its filename is
  // armed because the SQL body carries both PENDING-CODE-DEPLOY and
  // REQUIRES-DEPLOYED markers. Check the release checkout's git HEAD at the
  // runner's last safe point before the file can execute. The callback runs
  // only for files absent from schema_migrations, so an already-applied file
  // is never re-blocked merely because its companion later moved on.
  const deployedReleaseRoot = resolveDeployedReleaseRoot(sqlDir);
  const guardPendingMigration = (file: string, sqlText: string): void => {
    const verdict = verifyPendingCodeDeployMigration({
      filename: file,
      sqlText,
      releaseRoot: deployedReleaseRoot,
    });
    if (!verdict.ok) throw new Error(`[migration-deploy-guard] ${verdict.error}`);
  };

  // A DEDICATED max:1 client — the runner applies each file as a raw
  // `BEGIN; <ddl>; COMMIT;` via .unsafe(), which postgres-js rejects with
  // UNSAFE_TRANSACTION on a pooled (max>1) connection (it can't guarantee the
  // BEGIN/COMMIT land on the same socket). getOrgPg's shared handle is max:2,
  // so we use a throwaway single-connection client (mirrors the embedded-pg
  // boot runner + the migration tests) and close it after.
  // lock_timeout (root-caused 2026-06-08): fail-fast on lock contention instead
  // of queuing. A boot `ALTER TABLE … ADD COLUMN` needs ACCESS EXCLUSIVE; queued
  // behind a pg_dump backup's ACCESS SHARE it would block ALL access to the
  // table for the dump's duration (the coord_event_log → coord → psu-bootstrap
  // wedge). Boot apply is already continueOnError, so a lock_timeout abort just
  // leaves the (idempotent) migration pending for next boot. application_name
  // self-identifies a stuck boot migration in pg_stat_activity.
  const client = postgres(getHarnessAdminUrl(), {
    max: 1,
    prepare: false,
    onnotice: () => {},
    connection: { lock_timeout: 15_000, application_name: 'papercusp-boot-migrate' },
  });
  // EI-19403856469813053: load the cross-boot cooldown BEFORE attempting
  // anything, so a file that failed recently (elsewhere: a prior boot, or a
  // prior gate-preflight call) is excluded from this attempt entirely — it
  // never takes the ACCESS EXCLUSIVE lock at all this call, rather than
  // taking it again only to fail the same way. See the module-level comment
  // above MIGRATION_FAILURE_COOLDOWN_MS for the full rationale.
  const cooldownPath = resolveMigrationCooldownFilePath();
  const cooldownMs = resolveMigrationFailureCooldownMs();
  const cooldownState = await readMigrationCooldownState(cooldownPath);
  const cooldownNow = Date.now();
  const coolingDownEntries = Object.entries(cooldownState).filter(
    ([, entry]) => cooldownNow - entry.lastFailedAt < cooldownMs,
  );
  const coolingDown = new Map(coolingDownEntries);
  const skipFile = coolingDown.size > 0 ? (f: string) => defaultSkipFile(f) || coolingDown.has(f) : undefined;
  try {
    // Retry ONLY pure transaction contention (lock timeout / deadlock /
    // serialization). Any other failure — a syntax error, a constraint
    // violation, a genuinely broken migration — is a real defect that no
    // amount of retrying fixes, so it breaks out immediately and lands in the
    // existing leave-it-pending + broadcast path below, unchanged. Re-calling
    // applyPendingMigrations is safe and cheap: the schema_migrations tracker
    // makes already-applied files a no-op, so a retry re-attempts ONLY what is
    // still pending.
    let appliedCount = 0;
    let totalKnown = 0;
    let failed: { file: string; error: string }[] = [];
    for (let attempt = 1; attempt <= CONTENTION_RETRY_MAX_ATTEMPTS; attempt++) {
      const pass = await applyPendingMigrations({
        client,
        sqlDir,
        continueOnError: true,
        skipFile,
        beforeApply: guardPendingMigration,
        log: (s) => console.log(`[boot-migrate] ${s}`),
      });
      appliedCount += pass.appliedCount;
      totalKnown = pass.totalKnown;
      failed = pass.failed;
      if (failed.length === 0) break;
      const contentionOnly = failed.every((f) => isRetryableLockFailure(f.error ?? ''));
      if (!contentionOnly || attempt >= CONTENTION_RETRY_MAX_ATTEMPTS) break;
      const delayMs = contentionRetryBackoffMs(attempt);
      console.warn(
        `[boot-migrate] ${failed.length} migration(s) hit transaction contention ` +
          `(${failed.map((f) => `${f.file}: ${f.error}`).join('; ')}) — retrying in ${delayMs}ms ` +
          `(attempt ${attempt + 1}/${CONTENTION_RETRY_MAX_ATTEMPTS}); a deadlock is normally gone on the next try.`,
      );
      await sleep(delayMs);
    }
    // Merge the cooling-down files (skipped this call — never attempted, so
    // `failed` above has no entry for them) back in, so callers (the
    // green-checkpoint / checkpoint-run preflight included) still see them as
    // pending rather than silently vanishing from the report.
    if (coolingDown.size > 0) {
      const retryAfterEntries = coolingDownEntries.map(([file, entry]) => {
        const retryInSec = Math.max(1, Math.ceil((entry.lastFailedAt + cooldownMs - cooldownNow) / 1000));
        return {
          file,
          error: `skipped — cooling down after ${entry.attempts} prior boot-time failure(s) (last: ${entry.error}); retry in ~${retryInSec}s`,
        };
      });
      failed = [...retryAfterEntries, ...failed];
    }
    // Persist the cooldown: refresh every file that's freshly failing this
    // call (skips the just-merged cooling-down entries, which are unchanged),
    // and drop any tracked file that's no longer in `failed` at all (applied —
    // by this call, another boot, or db:migrate — the ledger is the source of
    // truth; this cooldown state is just an optimization on top of it).
    let cooldownChanged = false;
    for (const f of failed) {
      if (coolingDown.has(f.file)) continue;
      cooldownState[f.file] = {
        lastFailedAt: cooldownNow,
        error: f.error,
        attempts: (cooldownState[f.file]?.attempts ?? 0) + 1,
      };
      cooldownChanged = true;
    }
    for (const filename of Object.keys(cooldownState)) {
      if (!failed.some((f) => f.file === filename)) {
        delete cooldownState[filename];
        cooldownChanged = true;
      }
    }
    if (cooldownChanged) await writeMigrationCooldownState(cooldownPath, cooldownState);
    if (appliedCount > 0) {
      console.log(`[boot-migrate] applied ${appliedCount} pending migration(s) (of ${totalKnown} known)`);
    }
    if (failed.length > 0) {
      const files = failed.map((f) => f.file).join(', ');
      console.error(
        `[boot-migrate] ⚠ ${failed.length} migration(s) FAILED and were left pending (retried next boot): ${files}\n` +
          failed.map((f) => `    ${f.file}: ${f.error}`).join('\n'),
      );
      // Loud coord broadcast so peers see the broken migration (the dev-api
      // booted anyway). Ambient-categorised so it doesn't spam every inbox by
      // default but is opt-in visible (include_ambient) + in the coord stream.
      await sendMessage(BOOT_MIGRATE_IDENTITY, {
        to: ['*'],
        summary: `⚠ ${failed.length} migration(s) failed to apply on operator boot — left pending: ${files}`,
        body: `The native-box boot apply (A1) skipped these so the dev-api could start; they will retry next restart. Fix the SQL then restart the operator (or db:migrate). Errors:\n${failed
          .map((f) => `- ${f.file}: ${f.error}`)
          .join('\n')}`,
        category: 'service-health',
        // P-033 (d): `boot-migrate` does not match the conservative
        // MACHINE_SENDER_PATTERN — mark it machine chatter explicitly so the
        // sendMessage seam stamps `expects:'none'` (D-072).
        extra: { auto: true },
      }).catch(() => {});
    }
    // WI-5050 (WI-4070 class): detect the INVERSE drift — the shared DB was
    // migrated by a NEWER code tree than the one booting. Renames/drops that
    // newer tree performed have already executed, so THIS tree's queries can
    // hit `relation does not exist` at runtime and (worst case) the federation
    // plane dies silently — exactly how a stale dev-source tree (hives→pots,
    // mig-557) killed the VM peer with nothing but scattered PG errors. Loud
    // log + ambient coord broadcast; the operator still boots (the stale tree
    // may serve read paths fine and a refusal would take the whole box down).
    try {
      const drift = await checkMigrationDrift();
      if (drift.schemaAhead.length > 0) {
        const head = drift.schemaAhead.slice(0, 5).join(', ');
        console.error(
          `[boot-migrate] 🚨 SCHEMA AHEAD OF CODE: the DB has ${drift.schemaAhead.length} migration(s) NEWER than anything this code tree ships (${head}${drift.schemaAhead.length > 5 ? ', …' : ''}). ` +
            'This operator is running STALE CODE against a newer-migrated shared DB — expect `relation does not exist` failures on renamed tables and a silently-dead federation plane (WI-4070 class). ' +
            'Update/redeploy this code tree (stale dev-source / old bundle / lagging checkout) before trusting this host.',
        );
        await sendMessage(BOOT_MIGRATE_IDENTITY, {
          to: ['*'],
          summary: `🚨 schema AHEAD of code on operator boot: DB carries ${drift.schemaAhead.length} migration(s) newer than this code tree — stale operator (WI-4070 class), update/redeploy it`,
          body: `Newest DB-side migrations unknown to this tree: ${head}${drift.schemaAhead.length > 5 ? ', …' : ''}. A stale tree against a newer-migrated DB fails as scattered "relation does not exist" errors and can silently kill federation. Refresh the running code (dev-source tree / bundle / checkout), then restart.`,
          category: 'service-health',
        }).catch(() => {});
      }
    } catch {
      /* detection is best-effort — never blocks boot */
    }
    return { applied: appliedCount, failed };
  } catch (err) {
    console.error('[boot-migrate] boot apply failed (non-fatal):', err instanceof Error ? err.message : err);
    return null;
  } finally {
    await client.end({ timeout: 5 }).catch(() => {});
  }
}
