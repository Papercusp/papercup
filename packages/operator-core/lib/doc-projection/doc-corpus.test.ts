/**
 * The composed doc CORPUS — the DB-free subject the doc-claims guards judge
 * (plan claude-md-projection-from-pg-2026-08-10, P-004).
 *
 * Two jobs, and they are different in kind:
 *
 *  (1) FIXTURE CONTROLS for `composeCorpus` — the composition has one genuinely subtle
 *      property (the rule/evidence seam closes with NO separator) and one that the
 *      whole plan turns on (unprojected prose is INCLUDED). Both are asserted on
 *      synthetic input, so they keep proving the code works after the live assertions
 *      have gone green and stopped being evidence.
 *
 *  (2) A DRIFT ALARM over the committed artifacts. `CLAUDE.md` → the part manifest →
 *      the rows → this corpus is a chain, and each link is regenerated by a different
 *      command. Regenerate one alone and the set silently desynchronises: the guards
 *      then judge a corpus composed from a CLAUDE.md that no longer exists, and report
 *      a confident green about stale text. The source sha each artifact carries is what
 *      makes that decidable without a database.
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
// @ts-expect-error — .mjs script, no type declarations by design (it is a scripts/ tool). Keep this import on ONE line: a multi-line import under @ts-expect-error is a guaranteed tsc red (EI-19389216343173748).
import { composeCorpus, readCorpusProvenance, CORPUS_FILE, EVIDENCE_SUFFIX, PREAMBLE } from '../../../../scripts/project-doc-parts.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const MANIFEST = join(ROOT, 'packages/operator-core/lib/doc-projection/claude-md-part-manifest.json');
const CORPUS = join(ROOT, CORPUS_FILE as string);

type Part = { part_key: string; body: string; ordinal: number; client_scope: string[]; target_section: string | null };
const part = (p: Partial<Part> & { part_key: string; body: string }): Part => ({
  ordinal: 1,
  client_scope: [],
  target_section: 'S',
  ...p,
});

describe('composeCorpus — fixture controls', () => {
  it('closes the (rule, evidence) seam with NO separator', () => {
    // `ruleAndEvidence` guarantees rule + evidence === raw by arithmetic, so the halves
    // must be concatenated, not joined. Joining them the way blocks are joined would
    // fabricate a blank line that was never in the source and split one paragraph into
    // two — which markdown then renders, and the guards then parse, differently.
    const { text } = composeCorpus(
      [
        part({ part_key: 'a', body: 'The rule sentence.' }),
        part({ part_key: `a${EVIDENCE_SUFFIX}`, body: ' Measured: the evidence sentence.' }),
      ],
      { banner: false },
    );
    expect(text).toContain('The rule sentence. Measured: the evidence sentence.');
    expect(text).not.toContain('The rule sentence.\n\n Measured:');
  });

  it('INCLUDES unprojected parts — the entire reason this artifact exists', () => {
    const { text, blocks } = composeCorpus(
      [
        part({ part_key: 'inv', body: 'an invariant', client_scope: ['claude'], ordinal: 1 }),
        part({ part_key: 'prose', body: 'long-form prose', client_scope: [], ordinal: 2 }),
      ],
      { banner: false },
    );
    expect(text).toContain('an invariant');
    expect(text).toContain('long-form prose');
    expect(blocks).toBe(2);
  });

  it('emits a heading when the section changes, and never emits the preamble pseudo-section', () => {
    const { text } = composeCorpus(
      [
        part({ part_key: 'p', body: 'above the first heading', target_section: PREAMBLE, ordinal: 1 }),
        part({ part_key: 'a', body: 'first', target_section: 'Alpha', ordinal: 2 }),
        part({ part_key: 'b', body: 'second', target_section: 'Alpha', ordinal: 3 }),
        part({ part_key: 'c', body: 'third', target_section: 'Beta', ordinal: 4 }),
      ],
      { banner: false },
    );
    expect(text).toContain('## Alpha');
    expect(text).toContain('## Beta');
    expect(text).not.toContain(`## ${PREAMBLE as string}`);
    // One heading per section, not one per part.
    expect(text.match(/^## Alpha$/gm)).toHaveLength(1);
  });

  it('counts PARTS and BLOCKS as different quantities', () => {
    // A rule and its evidence are two parts but one block. Reporting either number as
    // the other is how "288 rows" and "253 blocks" get conflated in a status line.
    const { parts, blocks } = composeCorpus(
      [
        part({ part_key: 'a', body: 'rule' }),
        part({ part_key: `a${EVIDENCE_SUFFIX}`, body: ' evidence' }),
        part({ part_key: 'b', body: 'standalone', ordinal: 2 }),
      ],
      { banner: false },
    );
    expect(parts).toBe(3);
    expect(blocks).toBe(2);
  });

  it('a banner is machine-readable and round-trips its own provenance', () => {
    const { text } = composeCorpus([part({ part_key: 'a', body: 'x' })], { sourceSha: 'f'.repeat(64) });
    expect(readCorpusProvenance(text)).toEqual({ parts: 1, blocks: 1, sourceSha: 'f'.repeat(64) });
  });

  it('reports nulls rather than throwing when a file carries no provenance', () => {
    // Fail-soft on purpose: the drift assertions below turn a null into a NAMED failure.
    // Throwing here would surface as an unreadable stack instead.
    expect(readCorpusProvenance('# a document with no banner\n')).toEqual({ parts: null, blocks: null, sourceSha: null });
  });
});

