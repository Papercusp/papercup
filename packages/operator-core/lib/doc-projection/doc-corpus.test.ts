/**
 * The composed doc CORPUS — the DB-free subject the doc-claims guards judge
 * (plan claude-md-projection-from-pg-2026-08-10, P-004).
 *
 * Two jobs, and they are different in kind:
 *
 *  (1) FIXTURE CONTROLS for `composeCorpus` — the composition has one genuinely subtle
 *      property (the rule/evidence seam closes with NO separator) and one that the
 *      whole plan turns on (unprojected prose is INCLUDED). Both are asserted on
 *      synthetic input, so they keep proving the code works after the live assertions
 *      have gone green and stopped being evidence.
 *
 *  (2) A DRIFT ALARM over the committed artifacts. `CLAUDE.md` → the part manifest →
 *      the rows → this corpus is a chain, and each link is regenerated by a different
 *      command. Regenerate one alone and the set silently desynchronises: the guards
 *      then judge a corpus composed from a CLAUDE.md that no longer exists, and report
 *      a confident green about stale text. The source sha each artifact carries is what
 *      makes that decidable without a database.
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
// @ts-expect-error — .mjs script, no type declarations by design (it is a scripts/ tool). Keep this import on ONE line: a multi-line import under @ts-expect-error is a guaranteed tsc red (EI-19389216343173748).
import { composeCorpus, readCorpusProvenance, CORPUS_FILE, EVIDENCE_SUFFIX, PREAMBLE } from '../../../../scripts/project-doc-parts.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const MANIFEST = join(ROOT, 'packages/operator-core/lib/doc-projection/claude-md-part-manifest.json');
const CORPUS = join(ROOT, CORPUS_FILE as string);

type Part = { part_key: string; body: string; ordinal: number; client_scope: string[]; target_section: string | null };
const part = (p: Partial<Part> & { part_key: string; body: string }): Part => ({
  ordinal: 1,
  client_scope: [],
  target_section: 'S',
  ...p,
});

describe('composeCorpus — fixture controls', () => {
  it('closes the (rule, evidence) seam with NO separator', () => {
    // `ruleAndEvidence` guarantees rule + evidence === raw by arithmetic, so the halves
    // must be concatenated, not joined. Joining them the way blocks are joined would
    // fabricate a blank line that was never in the source and split one paragraph into
    // two — which markdown then renders, and the guards then parse, differently.
    const { text } = composeCorpus(
      [
        part({ part_key: 'a', body: 'The rule sentence.' }),
        part({ part_key: `a${EVIDENCE_SUFFIX}`, body: ' Measured: the evidence sentence.' }),
      ],
      { banner: false },
    );
    expect(text).toContain('The rule sentence. Measured: the evidence sentence.');
    expect(text).not.toContain('The rule sentence.\n\n Measured:');
  });

  it('INCLUDES unprojected parts — the entire reason this artifact exists', () => {
    const { text, blocks } = composeCorpus(
      [
        part({ part_key: 'inv', body: 'an invariant', client_scope: ['claude'], ordinal: 1 }),
        part({ part_key: 'prose', body: 'long-form prose', client_scope: [], ordinal: 2 }),
      ],
      { banner: false },
    );
    expect(text).toContain('an invariant');
    expect(text).toContain('long-form prose');
    expect(blocks).toBe(2);
  });

  it('emits a heading when the section changes, and never emits the preamble pseudo-section', () => {
    const { text } = composeCorpus(
      [
        part({ part_key: 'p', body: 'above the first heading', target_section: PREAMBLE, ordinal: 1 }),
        part({ part_key: 'a', body: 'first', target_section: 'Alpha', ordinal: 2 }),
        part({ part_key: 'b', body: 'second', target_section: 'Alpha', ordinal: 3 }),
        part({ part_key: 'c', body: 'third', target_section: 'Beta', ordinal: 4 }),
      ],
      { banner: false },
    );
    expect(text).toContain('## Alpha');
    expect(text).toContain('## Beta');
    expect(text).not.toContain(`## ${PREAMBLE as string}`);
    // One heading per section, not one per part.
    expect(text.match(/^## Alpha$/gm)).toHaveLength(1);
  });

  it('counts PARTS and BLOCKS as different quantities', () => {
    // A rule and its evidence are two parts but one block. Reporting either number as
    // the other is how "288 rows" and "253 blocks" get conflated in a status line.
    const { parts, blocks } = composeCorpus(
      [
        part({ part_key: 'a', body: 'rule' }),
        part({ part_key: `a${EVIDENCE_SUFFIX}`, body: ' evidence' }),
        part({ part_key: 'b', body: 'standalone', ordinal: 2 }),
      ],
      { banner: false },
    );
    expect(parts).toBe(3);
    expect(blocks).toBe(2);
  });

  it('a banner is machine-readable and round-trips its own provenance', () => {
    const { text } = composeCorpus([part({ part_key: 'a', body: 'x' })], { sourceSha: 'f'.repeat(64) });
    expect(readCorpusProvenance(text)).toEqual({ parts: 1, blocks: 1, sourceSha: 'f'.repeat(64) });
  });

  it('reports nulls rather than throwing when a file carries no provenance', () => {
    // Fail-soft on purpose: the drift assertions below turn a null into a NAMED failure.
    // Throwing here would surface as an unreadable stack instead.
    expect(readCorpusProvenance('# a document with no banner\n')).toEqual({ parts: null, blocks: null, sourceSha: null });
  });
});

describe('the committed corpus agrees with the committed manifest', () => {
  it('exists — the doc-claims guards read it, and an absent file makes them vacuous', () => {
    expect(existsSync(CORPUS)).toBe(true);
  });

  it('was composed from the SAME CLAUDE.md snapshot the manifest was cut from', () => {
    const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8')) as { snapshotSha256: string; parts: unknown[] };
    const prov = readCorpusProvenance(readFileSync(CORPUS, 'utf8'));
    expect(prov.sourceSha).toBe(manifest.snapshotSha256);
  });

  /*
   * POST-LOAD PART MUTATIONS.
   *
   * The manifest records the ONE-TIME cut from the hand-authored CLAUDE.md (its
   * `snapshotSha256`). Since the cutover, Postgres is canonical for parts and they
   * legitimately evolve — so "one block per manifest part" is a LOAD-TIME invariant that
   * the first deliberate part change necessarily breaks, permanently.
   *
   * Rather than relax this to a tolerance (which would stop catching silent loss — the
   * thing it exists for), every deliberate change is enumerated here with its reason and
   * its block delta. The assertion stays EXACT: anything going missing that is not listed
   * below still fails.
   */
  const POST_LOAD_BLOCK_DELTA = [
    {
      when: '2026-08-10',
      plan: 'claude-md-projection-from-pg-2026-08-10 P-018',
      // The `gen:tool-routing` generated block had been cut into 4 parts. Parts are joined
      // with a blank line, so the projection could not reproduce the block byte-exactly and
      // `npm run gen:tool-routing:check` failed against the projected CLAUDE.md. The block is
      // one generated unit whose exact bytes a build gate asserts, so it was merged into the
      // single BEGIN-marker part — atomic by construction, unsplittable by a future re-cut.
      why: 'merged the gen:tool-routing block into one atomic part (byte-fidelity)',
      // 4 parts merged into 1 => 3 fewer. One of the four was an `#evidence` part, which
      // composeCorpus folds into its parent and never counts as a block of its own; it was
      // also the half that was silently unprojected, which is what broke the block.
      blocksRemoved: 3,
    },
    {
      when: '2026-08-11',
      plan: 'acceptance-rubrics-on-every-plan-2026-08-11 P-006',
      // The acceptance-rubric mandate was ADDED as a new part in harness_doc_parts after the
      // manifest snapshot was frozen (the manifest is a P-014 migration artifact cut from the
      // pre-projection CLAUDE.md; it is NOT re-cut for post-load part changes — regenerating it
      // against today's PROJECTED file would drop every prose part, see the generator header).
      // A part added post-load is a block the manifest predates, so the delta is NEGATIVE: the
      // corpus legitimately carries one block more than the frozen part count.
      why: 'added the acceptance-rubric mandate part post-load (new CLAUDE.md section)',
      blocksRemoved: -1,
    },
    {
      when: '2026-08-21',
      plan: 'none — part authored directly into harness_doc_parts, projected in commit 09f2b5fc7b',
      // Same shape as the 2026-08-11 entry above: part `verify-mixed-family-work-item-citations`
      // ("Verify mixed-family work-item citations against the base table") was ADDED to
      // harness_doc_parts after the manifest snapshot was frozen, so the manifest predates it.
      // Verified rather than assumed: the manifest holds 253 partKeys, a known key
      // ('preamble-papercup-agent-guide') IS present, and BOTH post-load keys — this one and the
      // 2026-08-11 acceptance-rubric part — are absent from it. Hence the delta is NEGATIVE: the
      // corpus legitimately carries one block more than the frozen part count (252, not 251).
      why: 'added the mixed-family citation-verification part post-load (new CLAUDE.md section)',
      blocksRemoved: -1,
    },
  ] as const;

  it('has one block per manifest part, less deliberate post-load merges', () => {
    const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8')) as { parts: unknown[] };
    const prov = readCorpusProvenance(readFileSync(CORPUS, 'utf8'));
    const merged = POST_LOAD_BLOCK_DELTA.reduce((sum, d) => sum + d.blocksRemoved, 0);
    expect(
      prov.blocks,
      `corpus blocks (${prov.blocks}) != manifest parts (${manifest.parts.length}) - documented ` +
        `post-load merges (${merged}). If you deliberately changed the part set, add an entry to ` +
        `POST_LOAD_BLOCK_DELTA with its reason; otherwise blocks have gone missing.`,
    ).toBe(manifest.parts.length - merged);
  });

  it('is the WHOLE corpus, not the projected subset', () => {
    // The projected client file is ~57.8k of 166k. A corpus that had silently been
    // replaced by a projection would still be a large, plausible markdown file — the
    // size is the cheap tell, and the doc-claims floors are the real one.
    const text = readFileSync(CORPUS, 'utf8');
    expect(text.length).toBeGreaterThan(120_000);
  });
});
