/**
 * Edit-time guard for the SQL-comment-backtick class (EI-19457273276133433).
 *
 * WHY THIS EXISTS. Every pre-existing path that runs this detector — CI, the
 * git-sync content guard, green-checkpoint — fires at COMMIT time or later. But
 * `:3170` bundles the WORKING TREE, so a merely-SAVED backtick breaks the build
 * and crash-loops the whole fleet's staging host immediately. On 2026-08-03 that
 * took `papercup-staging-api` down 6× until systemd gave up, and it was at least
 * the 4th recurrence of this class.
 *
 * MEASURED, AND THE POINT OF THE WHOLE FILE: the offending bytes of that incident
 * are NOT REACHABLE FROM GIT HISTORY. The commit before the fix is clean — the
 * defect never got committed at all. So no commit-time guard could ever have seen
 * it, and no test built from git history can reproduce it. The fixture below is
 * reconstructed from the esbuild error the failing unit actually logged.
 *
 * ── The equivalence pin (read before "simplifying" this file) ───────────────
 * The predicate lives in ONE place, `scripts/lib/sql-comment-backtick-scan.mjs`,
 * precisely so the plain-`node` PreToolUse hook (which cannot import a `.ts`) and
 * the TypeScript ContentDetector run identical logic. The first test below pins
 * those two together on a shared fixture matrix. That pin is load-bearing: the
 * sibling smart-quotes rule in that same hook is a hand-port documented as "kept
 * in sync in spirit", which is exactly the drift this prevents. If you change the
 * heuristic, change the `.mjs` — never re-implement it in a consumer (D-003).
 */
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { findSqlCommentBacktick, sqlCommentBacktickScopeMatches } from './sql-comment-backtick';
import {
  findSqlCommentBacktick as findViaMjs,
  sqlCommentBacktickScopeMatches as scopeViaMjs,
} from '../../../../scripts/lib/sql-comment-backtick-scan.mjs';

const REPO_ROOT = fileURLToPath(new URL('../../../../', import.meta.url));
// Overridable so `scripts/mutation-probe.sh` can point the suite at a MUTATED COPY outside
// the tree and prove these cases are falsifiable — without ever mutating the shared tree
// (git-sync sweeps it every few minutes and would commit the mutant). Defaults to the real hook.
const HOOK =
  process.env.PROBE_CONTENT_LINT_HOOK ||
  path.join(REPO_ROOT, 'apps/operator/scripts/hooks/cc/pretooluse-content-lint.mjs');

// Built by char code so this test file never itself carries the pattern, and so the
// fixture is unambiguous to a human reader.
const BT = String.fromCharCode(96);

const withComment = (commentLine: string): string =>
  [
    'const rows = await sql' + BT,
    '    SELECT name, last_error FROM harness_shared.routines',
    '     WHERE active = true',
    commentLine,
    '     ORDER BY name ASC',
    '     LIMIT 200' + BT + ';',
  ].join('\n');

/** The real 2026-08-03 shape, reconstructed from the esbuild error text. */
const DEFECTIVE = withComment(
  '     -- Oldest error first, so the longest-standing failure is never crowded out; ' + BT + 'name' + BT,
);
/** The prescribed fix: same meaning, straight quotes. */
const REPHRASED = withComment(
  "     -- Oldest error first, so the longest-standing failure is never crowded out; the 'name' column",
);
/** A single backtick legitimately TERMINATING a one-line template — must not trip the >=2 rule. */
const SINGLE_BACKTICK = 'const q = ' + BT + 'SELECT 1 -- trailing comment' + BT + ';';
/** No SQL at all: the file-level scope gate should reject it before any line scan. */
const NO_SQL = 'export const n = 1;\n// -- not sql, just ' + BT + 'prose' + BT + ' in a JS comment\n';

const SUBJECT = 'packages/operator-core/lib/harness/improvements/watchdog.ts';

describe('sql-comment-backtick: one implementation, two consumers', () => {
  it('the .mjs scanner and the TS detector agree on every fixture (anti-drift pin)', () => {
    const fixtures: Array<[string, string]> = [
      ['defective', DEFECTIVE],
      ['rephrased', REPHRASED],
      ['single-backtick', SINGLE_BACKTICK],
      ['no-sql', NO_SQL],
    ];
    for (const [label, text] of fixtures) {
      const ts = findSqlCommentBacktick(SUBJECT, text);
      const mjs = findViaMjs(SUBJECT, text);
      expect(mjs, `${label}: .mjs and .ts must agree`).toEqual(ts);
    }
    const generatedWithShebang = '#!/usr/bin/env node\n/* @generated by apps/operator/bin/bundle-host.sh — do not edit */\n' + DEFECTIVE;
    expect(findViaMjs('dist-sidecar/embed-sidecar.mjs', generatedWithShebang)).toBeNull();
    expect(findSqlCommentBacktick('dist-sidecar/embed-sidecar.mjs', generatedWithShebang)).toBeNull();
    for (const p of [SUBJECT, 'a/b.test.ts', 'x/dist/y.mjs', 'z.d.ts', 'q.tsx']) {
      expect(scopeViaMjs(p), `scope must agree for ${p}`).toBe(sqlCommentBacktickScopeMatches(p));
    }
  });

  it('detects the real incident shape, and is quiet on the controls', () => {
    const hit = findViaMjs(SUBJECT, DEFECTIVE);
    expect(hit).not.toBeNull();
    expect(hit!.backticks).toBeGreaterThanOrEqual(2);
    expect(hit!.line).toBe(4);

    expect(findViaMjs(SUBJECT, REPHRASED)).toBeNull();
    expect(findViaMjs(SUBJECT, SINGLE_BACKTICK)).toBeNull();
    expect(findViaMjs(SUBJECT, NO_SQL)).toBeNull();
  });
});

describe('the PreToolUse hook BLOCKS the edit (the guard that was missing)', () => {
  const runHook = (filePath: string, content: string) => {
    const r = spawnSync('node', [HOOK], {
      input: JSON.stringify({ tool_name: 'Write', tool_input: { file_path: filePath, content } }),
      encoding: 'utf8',
      timeout: 20_000,
    });
    let decision = 'allow';
    try {
      decision = JSON.parse(r.stdout.trim() || '{}')?.hookSpecificOutput?.permissionDecision ?? 'allow';
    } catch {
      /* advisory text, or nothing: both mean allow */
    }
    return { decision, stdout: r.stdout };
  };

  const abs = (rel: string) => path.join(REPO_ROOT, rel);

  it('DENIES a write carrying the pattern', () => {
    const { decision, stdout } = runHook(abs(SUBJECT), DEFECTIVE);
    expect(decision).toBe('deny');
    // The reason must explain WHY it blocks rather than reports, or the next author
    // reads it as pedantry and works around it.
    expect(stdout).toContain('3170');
  });

  it('ALLOWS the rephrased fix, so the prescribed remedy is actually reachable', () => {
    expect(runHook(abs(SUBJECT), REPHRASED).decision).toBe('allow');
  });

  it('ALLOWS a legitimate single terminating backtick', () => {
    expect(runHook(abs(SUBJECT), SINGLE_BACKTICK).decision).toBe('allow');
  });

  it('ALLOWS test files — they carry deliberate fixtures of this exact bug', () => {
    expect(runHook(abs('packages/operator-core/lib/content-lint/ts-parse.test.ts'), DEFECTIVE).decision).toBe(
      'allow',
    );
  });
});

/**
 * RECURRENCE GUARD for EI-19492748262630855 — the hole that let this class recur on
 * 2026-08-04T02:03:50Z, 7.4h AFTER the guard above shipped, taking papercup-staging-api
 * down until systemd gave up (NRestarts=6) and quarantining a peer's fix for ~98min.
 *
 * WHY THE SUITE ABOVE STAYED GREEN THROUGH THAT. Every case above uses `Write`, whose
 * `tool_input.content` is the WHOLE FILE — the one tool shape that incidentally satisfies
 * the scanner's opening gate (`USES_SQL_TAG || HAS_RAW_DDL`). Real edits are `Edit`, whose
 * `new_string` is a FRAGMENT: inserting a comment into an existing sql`...` template sends
 * the scanner text with no sql tag in it (the opener was 65 lines away in the real
 * incident), so it returned null and the hook allowed the edit. The rule was inert for the
 * single most common way this defect is written, and no test could see it.
 *
 * These cases therefore assert on the `Edit`/`MultiEdit` shapes specifically, and pin the
 * property that makes them meaningful: THE FRAGMENT MUST NOT CONTAIN THE SQL TAG. Without
 * that assertion a later refactor could quietly turn these back into whole-content tests
 * and restore the blind spot with the suite still green.
 *
 * Hermetic by construction: a fake repo root under the OS temp dir, never the shared tree.
 * The tree-mutation shape (mutate a real file, restore afterwards) is banned here — git-sync
 * sweeps the whole tree every few minutes and would commit the mutant.
 */
describe('the hook scans the RESULTING FILE, not the edit fragment (EI-19492748262630855)', () => {
  const CLEAN_SQL_FILE = [
    'export async function q(sql: Sql) {',
    '  const rows = await sql' + BT,
    '    SELECT name, last_error FROM harness_shared.routines',
    '     WHERE active = true',
    '     ORDER BY name ASC',
    '     LIMIT 200' + BT + ';',
    '  return rows;',
    '}',
  ].join('\n');

  const ANCHOR = '     WHERE active = true';
  /** The fragment an agent actually writes: a comment line, and NOTHING else. */
  const FRAGMENT = ANCHOR + '\n     -- only the live ones; ' + BT + 'active' + BT + ' is the flag';

  let root: string;
  let subject: string;

  beforeAll(() => {
    root = mkdtempSync(path.join(tmpdir(), 'backtick-frag-guard-'));
    mkdirSync(path.join(root, 'scripts', 'lib'), { recursive: true });
    copyFileSync(
      path.join(REPO_ROOT, 'scripts/lib/sql-comment-backtick-scan.mjs'),
      path.join(root, 'scripts', 'lib', 'sql-comment-backtick-scan.mjs'),
    );
    const dir = path.join(root, 'packages', 'operator-core', 'lib', 'harness');
    mkdirSync(dir, { recursive: true });
    subject = path.join(dir, 'routines-read.ts');
    writeFileSync(subject, CLEAN_SQL_FILE, 'utf8');
  });

  afterAll(() => rmSync(root, { recursive: true, force: true }));

  const runEdit = (input: Record<string, unknown>, tool = 'Edit') => {
    const r = spawnSync('node', [HOOK], {
      input: JSON.stringify({ tool_name: tool, tool_input: { file_path: subject, ...input } }),
      encoding: 'utf8',
      timeout: 20_000,
    });
    try {
      return JSON.parse(r.stdout.trim() || '{}')?.hookSpecificOutput?.permissionDecision ?? 'allow';
    } catch {
      return 'allow';
    }
  };

  // CALIBRATION. If this ever fails, the cases below prove nothing: they would be passing
  // because the fragment carries the tag, not because the hook reconstructed the file.
  it('the fragment alone carries NO sql tag — the property under test', () => {
    expect(FRAGMENT).not.toContain('sql' + BT);
    expect(FRAGMENT).toContain(BT);
    // ...and the predicate is genuinely blind to it in isolation, which is the whole bug.
    expect(findSqlCommentBacktick('packages/operator-core/lib/harness/routines-read.ts', FRAGMENT)).toBeNull();
  });

  it('DENIES an Edit whose new_string alone would not trip the scanner', () => {
    expect(runEdit({ old_string: ANCHOR, new_string: FRAGMENT })).toBe('deny');
  });

  it('DENIES the same defect arriving via MultiEdit', () => {
    expect(runEdit({ edits: [{ old_string: ANCHOR, new_string: FRAGMENT }] }, 'MultiEdit')).toBe('deny');
  });

  it('ALLOWS an Edit that leaves the resulting file clean (no false positive)', () => {
    const ok = ANCHOR + "\n     -- only the live ones; the 'active' flag";
    expect(runEdit({ old_string: ANCHOR, new_string: ok })).toBe('allow');
  });

  it('ALLOWS an unrelated edit to a file that is ALREADY broken — never blame the wrong author', () => {
    const broken = path.join(root, 'packages', 'operator-core', 'lib', 'harness', 'already-broken.ts');
    writeFileSync(broken, CLEAN_SQL_FILE.replace(ANCHOR, FRAGMENT), 'utf8');
    const r = spawnSync('node', [HOOK], {
      input: JSON.stringify({
        tool_name: 'Edit',
        tool_input: { file_path: broken, old_string: '  return rows;', new_string: '  return rows; // touch' },
      }),
      encoding: 'utf8',
      timeout: 20_000,
    });
    let decision = 'allow';
    try {
      decision = JSON.parse(r.stdout.trim() || '{}')?.hookSpecificOutput?.permissionDecision ?? 'allow';
    } catch {
      /* allow */
    }
    expect(decision).toBe('allow');
  });
});
