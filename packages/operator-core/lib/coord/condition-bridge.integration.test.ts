/**
 * condition-bridge.integration.test.ts — P-008 of
 * `gate-ownership-condition-singleton-2026-08-03`, against REAL Postgres.
 *
 * WHY THIS FILE EXISTS AT ALL. Every other test in this plan is a unit test with
 * a faked store, and the three things this plan actually rests on are precisely
 * the three a faked store CANNOT evaluate:
 *
 *   1. P-002's PARTIAL UNIQUE INDEX. The bridge is deliberately optimistic —
 *      create, then try to take the key — because `work_items_condition_key_uq`
 *      serializes the winner in Postgres. A mock cannot serialize anything, so
 *      every unit test of `acquireConditionOwner` proves only that the CODE does
 *      what it says; it cannot prove the INDEX exists, that its predicate admits
 *      the rows it must, or that it refuses the second writer. The whole D-002
 *      thesis ("a check-then-act cannot be made safe by checking harder") is
 *      unverified without a real database. WI-6986 built this same dedup as a
 *      QUERY and duplicated "40 of 88 open rows" — that is what an unexercised
 *      index buys you.
 *
 *   2. The OPEN → RESOLVE → RE-OPEN cycle. Migration 741's longest comment is
 *      about why the index predicate is `condition_key IS NOT NULL` and not
 *      `closed_ts IS NULL`. Under the rejected predicate, the SECOND occurrence
 *      of any condition hits a unique violation against the settled row and that
 *      condition becomes permanently unownable — a failure invisible until a
 *      condition recurs, possibly weeks later. Only a real index can fail that
 *      way, so only a real index can be shown not to.
 *
 *   3. D-020's settle gate. `isBridgeMinted` reads `payload -> '_bridge'` out of
 *      Postgres, and the marker is written by `createWorkItem` → `createIssue`,
 *      three layers down, through a `::text::jsonb` cast. Whether the stamp
 *      SURVIVES that round-trip is a storage question. Migration 742's backfill
 *      was verified live; the MINT path's stamping never was.
 *
 * Run with:
 *   npm run test:file -- packages/operator-core/lib/coord/condition-bridge.integration.test.ts
 */
