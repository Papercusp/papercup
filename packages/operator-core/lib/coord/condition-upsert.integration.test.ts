describe('upsertConditionWorkItem — the WI-39594 acceptance', () => {
  it('re-firing the same condition twice yields ONE open item, refreshed to the newest reading', async () => {
    const KEY = 'detector-test:refire';
    const first = await upsertConditionWorkItem(KEY, spec('reading 1: leg A failed (t1)'));
    expect(first.created).toBe(true);
    expect(first.id).toBeTruthy();

    const second = await upsertConditionWorkItem(KEY, spec('reading 2: leg A failed (t2)'));
    expect(second.created).toBe(false);
    expect(second.id).toBe(first.id);

    const open = await openItemsFor(KEY);
    expect(open).toHaveLength(1); // the acceptance criterion, verbatim
    expect(open[0].feature_id).toBe(first.id);
    expect(open[0].title).toBe('reading 2: leg A failed (t2)'); // newest reading wins
    expect(open[0].occurrences).toBe(2);
    expect(await holdersOf(KEY)).toEqual([first.id]);
    expect((await findConditionObject(KEY, { harnessSlug: H })).workItem).toBe(first.id);
  });

  it('CONCURRENT filers: the unique index serializes to one open owner; losers settle themselves', async () => {
    const KEY = 'detector-test:race';
    const results = await Promise.all([
      upsertConditionWorkItem(KEY, spec('racer 1')),
      upsertConditionWorkItem(KEY, spec('racer 2')),
      upsertConditionWorkItem(KEY, spec('racer 3')),
      upsertConditionWorkItem(KEY, spec('racer 4')),
    ]);
    const holders = await holdersOf(KEY);
    expect(holders).toHaveLength(1);
    // Every result converged on the one owner (unless a stand-down failed, which
    // must then be REPORTED, not silent).
    for (const r of results) {
      if (r.duplicateLeftOpen) continue;
      expect(r.id).toBe(holders[0]);
    }
    const open = await openItemsFor(KEY);
    const undeclaredDupes = open.filter(
      (o) => o.feature_id !== holders[0] && !results.some((r) => r.duplicateLeftOpen === o.feature_id),
    );
    expect(undeclaredDupes).toEqual([]);
  });

  it('a SETTLED owner does not wedge the key: the next occurrence self-heals and mints fresh', async () => {
    const KEY = 'detector-test:recur';
    const first = await upsertConditionWorkItem(KEY, spec('episode 1'));
    expect(first.created).toBe(true);
    // Settle WITHOUT releasing the key — the missed-release crash shape.
    await setWorkItemState(first.id!, 'done', { harness: H, by: 'system:test', completionRef: 'fixed' });

    const second = await upsertConditionWorkItem(KEY, spec('episode 2'));
    expect(second.created).toBe(true);
    expect(second.id).not.toBe(first.id);
    const open = await openItemsFor(KEY);
    expect(open).toHaveLength(1);
    expect(open[0].feature_id).toBe(second.id);
    expect((await findConditionObject(KEY, { harnessSlug: H })).workItem).toBe(second.id);
  });
});

describe('createOneWorkItem { conditionKey } — the WI-39604 tool-path leg', () => {
  const ctx = { ownerId: 'system:live-federation-gate', workspaceId: WS, harnessSlug: H };

  it('re-firing through the TOOL CORE twice yields ONE open item, refreshed to the newest reading (the gate-script contract)', async () => {
    const KEY = 'live-federation-gate-red:test-papercusp';
    const first = await createOneWorkItem(
      {
        kind: 'bug',
        title: 'live-federation-gate RED: content-matrix failed (t1)',
        summary: 'legs: content-matrix',
        harness: H,
        severity: 'major',
        conditionKey: KEY,
      },
      ctx,
    );
    expect(first.ok).toBe(true);
    if (!first.ok) return;
    expect(first.conditionUpsert).toBeUndefined(); // a fresh mint is an ordinary create
    expect(await holdersOf(KEY)).toEqual([first.workItem.id]);

    const second = await createOneWorkItem(
      {
        kind: 'bug',
        title: 'live-federation-gate RED: from-repo failed (t2)',
        summary: 'legs: from-repo',
        harness: H,
        severity: 'major',
        conditionKey: KEY,
      },
      ctx,
    );
    expect(second.ok).toBe(true);
    if (!second.ok) return;
    expect(second.conditionUpsert?.adopted).toBe(true);
    expect(second.workItem.id).toBe(first.workItem.id);

    const open = await openItemsFor(KEY);
    expect(open).toHaveLength(1); // dupes cannot leak across marker-expiry days: one row per condition
    expect(open[0].feature_id).toBe(first.workItem.id);
    expect(open[0].title).toBe('live-federation-gate RED: from-repo failed (t2)'); // newest legs+stamp win
    expect(open[0].occurrences).toBe(2);
    expect((await findConditionObject(KEY, { harnessSlug: H })).workItem).toBe(first.workItem.id);
  });

  it('a tool-core create JOINS a row minted by upsertConditionWorkItem — one key, either filer', async () => {
    const KEY = 'detector-test:cross-filer';
    const seeded = await upsertConditionWorkItem(KEY, spec('seeded by the module (t1)'));
    expect(seeded.created).toBe(true);

    const viaTool = await createOneWorkItem(
      { kind: 'bug', title: 'refiled via the tool (t2)', harness: H, severity: 'major', conditionKey: KEY },
      ctx,
    );
    expect(viaTool.ok).toBe(true);
    if (!viaTool.ok) return;
    expect(viaTool.conditionUpsert?.adopted).toBe(true);
    expect(viaTool.workItem.id).toBe(seeded.id);
    expect(await openItemsFor(KEY)).toHaveLength(1);
  });
});
