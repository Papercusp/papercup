/**
 * EI-1 (P-020 / D-027 / D-028) — feature→feature blocking on coord_links rel='blocks'
 * edges, now the SINGLE source of truth (the legacy `blocked_by` column + its GIN
 * index were dropped, migration 155). Proves: edge writes via syncFeatureBlockEdges
 * round-trip through getFeatureBlockers, and the dispatch frontier
 * (readFrontierFeatures) derives each feature's blockedBy from the edges.
 *
 * Real PG (throwaway DB); getOrgPg mocked at it, mirroring issues-engineer.integration.
 */
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { createFreshPgDb, type FreshPgDb } from '../../test/_pg-helpers';

const h: { sql: FreshPgDb['sql'] } = { sql: null as never };

vi.mock('@papercusp/db-org', async () => {
  const actual = await vi.importActual<typeof import('@papercusp/db-org')>('@papercusp/db-org');
  return { ...actual, getOrgPg: () => ({ sql: h.sql }) };
});

import { getFeatureBlockers, featureBlockEdges, syncFeatureBlockEdges } from './feature-blockers-edges';
import { readFrontierFeatures } from './orchestrator-loop';

let db: FreshPgDb;

beforeAll(async () => {
  db = await createFreshPgDb('ei1-feature-blockers');
  h.sql = db.sql;
  // coord_links (migration 123 shape) + its unique edge index, plus the post-155
  // feature surface: NO blocked_by column (blocking lives in coord_links), with the
  // item_kind discriminator + the work_items view the frontier reads (kind-scoped).
  await db.sql.unsafe(`
    CREATE TABLE IF NOT EXISTS harness_shared.coord_links (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id text DEFAULT 'default' NOT NULL,
      src_kind text NOT NULL, src_ref text NOT NULL,
      dst_kind text NOT NULL, dst_ref text NOT NULL,
      rel text NOT NULL, created_by text, created_at timestamptz DEFAULT now() NOT NULL);
    CREATE UNIQUE INDEX IF NOT EXISTS coord_links_edge_uq
      ON harness_shared.coord_links (workspace_id, src_kind, src_ref, dst_kind, dst_ref, rel);
    CREATE TABLE IF NOT EXISTS harness_shared.harness_features_consolidated (
      workspace_id text NOT NULL, harness_slug text NOT NULL, feature_id text NOT NULL,
      status text, feature_order int, metadata jsonb,
      item_kind text NOT NULL DEFAULT 'feature',
      origin text DEFAULT 'local', audit_verdict text,
      PRIMARY KEY (workspace_id, harness_slug, feature_id));
    CREATE TABLE IF NOT EXISTS harness_shared.harness_plans (
      workspace_id text, harness_slug text, plan_slug text, op_status text);
    CREATE OR REPLACE VIEW harness_shared.work_items AS
      SELECT * FROM harness_shared.harness_features_consolidated;
  `);
}, 90_000);

afterAll(async () => {
  await db.cleanup();
});

beforeEach(async () => {
  await db.sql`TRUNCATE harness_shared.coord_links, harness_shared.harness_features_consolidated RESTART IDENTITY`;
});

// Seed features (no blocked_by column post-155) + their blocker edges via the real
// write path (syncFeatureBlockEdges — what the feature import now calls).
async function seed(rows: { id: string; blockedBy?: string[]; status?: string }[]) {
  for (const r of rows) {
    await db.sql`
      INSERT INTO harness_shared.harness_features_consolidated
        (workspace_id, harness_slug, feature_id, status, item_kind, origin)
      VALUES ('default', 'demo', ${r.id}, ${r.status ?? 'todo'}, 'feature', 'local')`;
    if (r.blockedBy && r.blockedBy.length > 0) await syncFeatureBlockEdges('demo', r.id, r.blockedBy);
  }
}

const sortMap = (m: Map<string, string[]>) =>
  Object.fromEntries([...m].map(([k, v]) => [k, [...v].sort()]).sort());

describe('featureBlockEdges (pure)', () => {
  it('expands blocker ids into harness-qualified blocks edges (drops self + empty)', () => {
    const edges = featureBlockEdges('demo', 'F-1', ['F-2', ' F-3 ', '', 'F-1']);
    expect(edges.map((e) => [e.src_ref, e.dst_ref, e.rel, e.src_kind, e.dst_kind])).toEqual([
      ['demo#F-2', 'demo#F-1', 'blocks', 'feature', 'feature'],
      ['demo#F-3', 'demo#F-1', 'blocks', 'feature', 'feature'],
    ]);
  });
});

describe('EI-1 edge blocking (real PG)', () => {
  it('syncFeatureBlockEdges writes/replaces/clears a feature’s blocker edges; getFeatureBlockers reads them', async () => {
    await syncFeatureBlockEdges('demo', 'F-1', ['F-2', 'F-3']);
    expect(sortMap(await getFeatureBlockers('demo'))).toEqual({ 'F-1': ['F-2', 'F-3'] });
    // Update: F-1 now blocked only by F-4 → old edges gone, new present.
    await syncFeatureBlockEdges('demo', 'F-1', ['F-4']);
    expect(sortMap(await getFeatureBlockers('demo'))).toEqual({ 'F-1': ['F-4'] });
    // Cleared: no blockers → no edges.
    await syncFeatureBlockEdges('demo', 'F-1', []);
    expect(sortMap(await getFeatureBlockers('demo'))).toEqual({});
  });

  it('getFeatureBlockers drops self-edges + dedups, scoped within the harness', async () => {
    await syncFeatureBlockEdges('demo', 'F-3', ['F-1', 'F-2', 'F-3']); // self-edge dropped at write
    expect(sortMap(await getFeatureBlockers('demo'))).toEqual({ 'F-3': ['F-1', 'F-2'] });
  });

  it('the dispatch frontier derives each feature’s blockedBy from the coord_links edges', async () => {
    await seed([
      { id: 'F-1', blockedBy: ['F-2'] },
      { id: 'F-2' },
      { id: 'F-3', blockedBy: ['F-1', 'F-2'] },
    ]);
    const frontier = await readFrontierFeatures(db.sql as never, 'default', 'demo');
    const norm = (fs: { id: string; blockedBy: readonly string[] }[]) =>
      Object.fromEntries(fs.map((f) => [f.id, [...f.blockedBy].sort()]).sort());
    expect(norm(frontier)).toEqual({ 'F-1': ['F-2'], 'F-2': [], 'F-3': ['F-1', 'F-2'] });
  });
});
