/**
 * Acyclicity enforced on the AUTHORITATIVE feature→feature `blocks` write
 * (work-item-deps-and-readiness-2026-06-22 P-003, audit finding F4) — against REAL Postgres.
 *
 * A feature→feature `blocks` CYCLE silently DEADLOCKS the scheduler frontier (every item in the
 * cycle is forever non-ready, because its blocker never terminates). The authoritative writer is
 * `syncFeatureBlockEdges` (coord_links rel='blocks'); this proves it now REJECTS a cycle-closing
 * blocker set and leaves the graph untouched, while accepting a DAG. Mirrors the sibling
 * feature-blockers-edges.integration.test.ts setup (coord_links + work_item_deps + the features view).
 *
 * Real PG (throwaway DB; Docker required); getOrgPg mocked at it.
 *
 * Run:
 *   cd packages/operator-core && npx vitest run --config vitest.integration.config.ts \
 *     lib/dbos/feature-blockers-acyclicity.integration.test.ts
 */
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { createFreshPgDb, type FreshPgDb } from '../../test/_pg-helpers';
import { HARNESS_FEATURES_CONSOLIDATED_DDL, WORK_ITEM_DEPS_DDL } from '../../test/_work-items-schema';

const h: { sql: FreshPgDb['sql'] } = { sql: null as never };

vi.mock('@papercusp/db-org', async () => {
  const actual = await vi.importActual<typeof import('@papercusp/db-org')>('@papercusp/db-org');
  return { ...actual, getOrgPg: () => ({ sql: h.sql }) };
});

const {
  getFeatureBlockers,
  syncFeatureBlockEdges,
  detectFeatureBlockGraphCycle,
} = await import('./feature-blockers-edges');

let db: FreshPgDb;
const H = 'demo';

beforeAll(async () => {
  db = await createFreshPgDb('feature-blockers-acyclicity');
  h.sql = db.sql;
  // coord_links (migration 123 shape) + its unique edge index — the table syncFeatureBlockEdges
  // writes and getFeatureBlockers reads.
  await db.sql.unsafe(`
    CREATE TABLE IF NOT EXISTS harness_shared.coord_links (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      workspace_id text DEFAULT 'default' NOT NULL,
      src_kind text NOT NULL, src_ref text NOT NULL,
      dst_kind text NOT NULL, dst_ref text NOT NULL,
      rel text NOT NULL, created_by text, created_at timestamptz DEFAULT now() NOT NULL);
    CREATE UNIQUE INDEX IF NOT EXISTS coord_links_edge_uq
      ON harness_shared.coord_links (workspace_id, src_kind, src_ref, dst_kind, dst_ref, rel);
  `);
  await db.sql.unsafe(HARNESS_FEATURES_CONSOLIDATED_DDL);
  await db.sql.unsafe(WORK_ITEM_DEPS_DDL).simple(); // syncFeatureBlockEdges' transitional dual-write target
}, 90_000);

afterAll(async () => {
  await db.cleanup();
});

beforeEach(async () => {
  await db.sql`TRUNCATE harness_shared.coord_links, harness_shared.work_items RESTART IDENTITY`;
});

const sortMap = (m: Map<string, string[]>) =>
  Object.fromEntries([...m].map(([k, v]) => [k, [...v].sort()]).sort());

describe('syncFeatureBlockEdges enforces acyclicity (P-003 / F4) — real PG', () => {
  it('ACCEPTS a DAG (a chain) and round-trips it', async () => {
    // A<-B<-C : C blocks B blocks A. Acyclic.
    await syncFeatureBlockEdges(H, 'A', ['B']);
    await syncFeatureBlockEdges(H, 'B', ['C']);
    expect(sortMap(await getFeatureBlockers(H))).toEqual({ A: ['B'], B: ['C'] });
    // Reconciliation read sees no cycle.
    expect((await detectFeatureBlockGraphCycle(H)).hasCycle).toBe(false);
  });

  it('REJECTS a cycle-closing edge  a→b→a  and leaves the graph untouched', async () => {
    await syncFeatureBlockEdges(H, 'A', ['B']); // B blocks A
    // Now try to make A block B too (A blocked-by B already; B blocked-by A closes the 2-cycle).
    await expect(syncFeatureBlockEdges(H, 'B', ['A'])).rejects.toThrow(/dependency cycle/);
    // The rejected write did not partially apply: only the original edge remains.
    expect(sortMap(await getFeatureBlockers(H))).toEqual({ A: ['B'] });
    expect((await detectFeatureBlockGraphCycle(H)).hasCycle).toBe(false);
  });

  it('REJECTS a transitive cycle-closing edge  a→b→c→a', async () => {
    await syncFeatureBlockEdges(H, 'A', ['B']); // A<-B
    await syncFeatureBlockEdges(H, 'B', ['C']); // B<-C
    // Closing C<-A makes C→B→A→C.
    await expect(syncFeatureBlockEdges(H, 'C', ['A'])).rejects.toThrow(/dependency cycle/);
    expect(sortMap(await getFeatureBlockers(H))).toEqual({ A: ['B'], B: ['C'] });
  });

  it('a SELF-block is dropped (no edge written), not a cycle error', async () => {
    await syncFeatureBlockEdges(H, 'A', ['A', 'B']); // self-edge dropped; B kept
    expect(sortMap(await getFeatureBlockers(H))).toEqual({ A: ['B'] });
  });

  it('enforceAcyclicity:false bypasses the guard (the trusted-backfill escape hatch)', async () => {
    await syncFeatureBlockEdges(H, 'A', ['B']);
    // With the guard disabled, the cycle-closing edge IS written (used only for validated backfills).
    await syncFeatureBlockEdges(H, 'B', ['A'], { enforceAcyclicity: false });
    expect(sortMap(await getFeatureBlockers(H))).toEqual({ A: ['B'], B: ['A'] });
    // And the read-only reconciliation helper now FLAGS the pre-existing cycle.
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
    const r = await detectFeatureBlockGraphCycle(H);
    expect(r.hasCycle).toBe(true);
    expect(r.cycleNodes.sort()).toEqual(['A', 'B']);
    warn.mockRestore();
  });
});
