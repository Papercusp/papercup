/**
 * Guard for WI-4978 (Papercusp org vs papercupai login identity confusion).
 *
 * The canonical product repositories live under the `Papercusp` GitHub
 * Organization; `papercupai` is a GitHub User (the maintainer's personal
 * admin login) and does not own product repos. At least one owner-facing
 * link (`apps/operator/app/support/page.tsx`'s "Open a GitHub issue" button)
 * hardcoded `github.com/papercupai/papercusp` — a repo that has never
 * existed under that owner, so the link 404s. See
 * `canonical-github-identity.ts` for the single source of truth these links
 * should be built from.
 *
 * This test fails the build the moment a NEW hardcoded
 * `github.com/papercupai/<papercup-or-papercusp>` link is committed anywhere
 * in the tree, tracked file or fresh-but-untracked (a brand new file is
 * exactly where a fresh identity mix-up is most likely to land — see
 * `listFilesIncludingUntracked`'s own rationale).
 *
 * Deliberately narrow: `papercupai/<anything-else>` is NOT flagged, because
 * several tests (e.g. `operator-public/src/__tests__/listings.test.ts`) use
 * `papercupai` as a generic example GitHub username in fixture data — that
 * is unrelated to this product's own identity and would be a false positive.
 * What's unambiguous, and the actual bug class observed live, is `papercupai`
 * paired with THIS product's own repo name.
 */
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
// eslint-disable-next-line import/no-relative-packages
import { listFilesIncludingUntracked } from '../../../scripts/lib/tracked-files.mjs';

const ROOT = join(__dirname, '../../..');

/** Matches the exact wrong pattern: papercupai treated as the owner of the product repo. */
const WRONG_OWNER_REPO = /github\.com\/papercupai\/(papercup|papercusp)\b/i;

/**
 * Generated build-output mirrors (Starlight `dist`/preview + the operator's
 * committed public/docs and public/internal/docs static mirrors) reflect
 * whatever the source docs said at last build time — they are regenerated by
 * `npm run build`, never hand-edited, and are therefore not a source of
 * truth to guard here. Guard the SOURCE files that actually produce them.
 */
const EXCLUDED_PATH_SEGMENTS = [
  '/dist/',
  '/dist-preview/',
  'apps/operator/public/docs/',
  'apps/operator/public/internal/docs/',
  // this file's own explanatory comments quote the wrong pattern as an example
  'packages/operator-core/lib/github-identity-drift.test.ts',
];

const TEXT_EXTENSIONS = /\.(ts|tsx|js|jsx|mjs|cjs|mdx|md|astro|json|html)$/i;

describe('github identity drift guard (WI-4978)', () => {
  it('no source file links to papercupai as if it owned the product repo', () => {
    const { files } = listFilesIncludingUntracked(ROOT) as { files: string[] };
    const offenders: Array<{ path: string; line: number; text: string }> = [];

    for (const relPath of files) {
      if (!TEXT_EXTENSIONS.test(relPath)) continue;
      if (EXCLUDED_PATH_SEGMENTS.some((seg) => relPath.includes(seg))) continue;

      let content: string;
      try {
        content = readFileSync(join(ROOT, relPath), 'utf8');
      } catch {
        continue; // symlink / race / binary — not this guard's concern
      }
      if (!WRONG_OWNER_REPO.test(content)) continue;

      content.split('\n').forEach((line, idx) => {
        if (WRONG_OWNER_REPO.test(line)) {
          offenders.push({ path: relPath, line: idx + 1, text: line.trim() });
        }
      });
    }

    if (offenders.length > 0) {
      const detail = offenders
        .map((o) => `  ${o.path}:${o.line}: ${o.text}`)
        .join('\n');
      throw new Error(
        `Found ${offenders.length} link(s) pointing to papercupai as if it owned the product repo ` +
          `(the canonical org is 'Papercusp', repo 'papercup' — see canonical-github-identity.ts):\n${detail}`,
      );
    }

    expect(offenders).toEqual([]);
  });

  it('the canonical constants resolve to the real remote (Papercusp/papercup)', async () => {
    const {
      GITHUB_ORG,
      GITHUB_REPO,
      GITHUB_REPO_SLUG,
      GITHUB_REPO_URL,
      GITHUB_ISSUES_URL,
      GITHUB_NEW_ISSUE_URL,
      GITHUB_MAINTAINER_LOGIN,
    } = await import('./canonical-github-identity');

    expect(GITHUB_ORG).toBe('Papercusp');
    expect(GITHUB_REPO).toBe('papercup');
    expect(GITHUB_REPO_SLUG).toBe('Papercusp/papercup');
    expect(GITHUB_REPO_URL).toBe('https://github.com/Papercusp/papercup');
    expect(GITHUB_ISSUES_URL).toBe('https://github.com/Papercusp/papercup/issues');
    expect(GITHUB_NEW_ISSUE_URL).toBe('https://github.com/Papercusp/papercup/issues/new');
    // The maintainer's personal login is a distinct, deliberately-not-org identity.
    expect(GITHUB_MAINTAINER_LOGIN).toBe('papercupai');
    expect(GITHUB_MAINTAINER_LOGIN).not.toBe(GITHUB_ORG);
  });
});
